import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import DataTransferPanel from './DataTransferPanel'
import { clearAllData, exportData, importData } from './db'
import { decryptBackup, encryptBackup } from './cryptoBackup'

vi.mock('./db', () => ({ clearAllData: vi.fn(), exportData: vi.fn(), importData: vi.fn() }))
vi.mock('./cryptoBackup', () => ({ decryptBackup: vi.fn(), encryptBackup: vi.fn() }))

const rawBackup = '{"version":2,"conversations":{},"memories":[],"settings":{}}'
const encryptedBackup = '{"format":"aily-encrypted-backup","data":"ciphertext"}'
const importedData = { conversations: {}, memories: [], summaries: [], settings: {} }
const createObjectURL = vi.fn(), revokeObjectURL = vi.fn()

beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(exportData).mockResolvedValue(rawBackup)
  vi.mocked(importData).mockResolvedValue(importedData)
  vi.mocked(clearAllData).mockResolvedValue(undefined)
  vi.mocked(encryptBackup).mockResolvedValue(encryptedBackup)
  vi.mocked(decryptBackup).mockResolvedValue(rawBackup)
  createObjectURL.mockReturnValue('blob:encrypted-backup')
  vi.stubGlobal('URL', { createObjectURL, revokeObjectURL })
  vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
})
afterEach(() => {
  cleanup()
  vi.clearAllTimers()
  vi.useRealTimers()
  vi.restoreAllMocks()
  vi.unstubAllGlobals()
})

function setup(beforeDataChange = vi.fn<() => Promise<void>>().mockResolvedValue(undefined)) {
  const onImported = vi.fn(), onCleared = vi.fn()
  render(<DataTransferPanel beforeDataChange={beforeDataChange} onImported={onImported} onCleared={onCleared} />)
  return { beforeDataChange, onImported, onCleared }
}
const password = (value: string) => fireEvent.change(screen.getByLabelText('备份密码'), { target: { value } })
function chooseFile(contents = encryptedBackup) {
  const file = new File([contents], 'saved-backup.json', { type: 'application/json' })
  // jsdom's File lacks text(); supply the same async interface used in browsers.
  const text = vi.fn().mockResolvedValue(contents)
  Object.defineProperty(file, 'text', { value: text })
  fireEvent.change(screen.getByLabelText('导入备份文件'), { target: { files: [file] } })
  return { file, text }
}
const requestImport = () => fireEvent.click(screen.getByRole('button', { name: '导入并替换本机数据' }))
const confirmImport = () => fireEvent.click(screen.getByRole('button', { name: '确认替换' }))
const requestClear = () => fireEvent.click(screen.getByRole('button', { name: '清空本机聊天与记忆' }))
const confirmClear = () => fireEvent.click(screen.getByRole('button', { name: '确认清空' }))
function deferred() {
  let resolve!: () => void
  const promise = new Promise<void>(done => { resolve = done })
  return { promise, resolve }
}

describe('local encrypted data transfer', () => {
  it.each(['import', 'clear'] as const)('focuses the %s confirmation and restores its trigger on cancel', operation => {
    setup()
    chooseFile()
    const trigger = screen.getByRole('button', { name: operation === 'import' ? '导入并替换本机数据' : '清空本机聊天与记忆' })
    trigger.focus()
    expect(trigger).toHaveFocus()
    fireEvent.click(trigger)
    const group = screen.getByRole('group', { name: operation === 'import' ? '确认导入备份' : '确认清空聊天' })
    expect(group).toHaveAttribute('tabindex', '-1')
    expect(group).toHaveFocus()
    const cancel = screen.getByRole('button', { name: '取消' })
    cancel.focus()
    fireEvent.click(cancel)
    expect(group).not.toBeInTheDocument()
    expect(trigger).toBeEnabled()
    expect(trigger).toHaveFocus()
  })

  it('returns focus to the file picker after a successful import disables its trigger', async () => {
    setup()
    chooseFile()
    const trigger = screen.getByRole('button', { name: '导入并替换本机数据' })
    trigger.focus(); requestImport()
    expect(screen.getByRole('group', { name: '确认导入备份' })).toHaveFocus()
    const confirm = screen.getByRole('button', { name: '确认替换' })
    confirm.focus(); fireEvent.click(confirm)
    await screen.findByRole('status')
    expect(trigger).toBeDisabled()
    expect(screen.getByLabelText('导入备份文件')).toHaveFocus()
  })

  it('returns focus to the clear trigger after a successful clear', async () => {
    setup()
    const trigger = screen.getByRole('button', { name: '清空本机聊天与记忆' })
    trigger.focus(); requestClear()
    expect(screen.getByRole('group', { name: '确认清空聊天' })).toHaveFocus()
    const confirm = screen.getByRole('button', { name: '确认清空' })
    confirm.focus(); fireEvent.click(confirm)
    await screen.findByRole('status')
    expect(trigger).toBeEnabled()
    expect(trigger).toHaveFocus()
  })

  it.each(['', '12345'])('rejects export password %j before touching local data', async value => {
    const { beforeDataChange } = setup()
    password(value)
    fireEvent.click(screen.getByRole('button', { name: '导出加密备份' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('请设置至少 6 位的备份密码')
    expect(beforeDataChange).not.toHaveBeenCalled()
    expect(exportData).not.toHaveBeenCalled()
    expect(encryptBackup).not.toHaveBeenCalled()
    expect(createObjectURL).not.toHaveBeenCalled()
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    expect(screen.getByLabelText('备份密码')).toHaveValue(value)
    expect(screen.getByRole('button', { name: '导出加密备份' })).toBeEnabled()
  })

  it('waits for local writes, exports only ciphertext and guards duplicate/busy actions', async () => {
    vi.useFakeTimers()
    const pending = deferred()
    const { beforeDataChange, onImported, onCleared } = setup(vi.fn().mockReturnValue(pending.promise))
    password('secret')
    const exportButton = screen.getByRole('button', { name: '导出加密备份' })
    fireEvent.click(exportButton)
    fireEvent.click(exportButton)
    expect(beforeDataChange).toHaveBeenCalledTimes(1)
    expect(exportData).not.toHaveBeenCalled()
    expect(screen.getByRole('region', { name: '本机聊天与记忆' })).toHaveAttribute('aria-busy', 'true')
    expect(screen.getByRole('button', { name: '正在加密导出…' })).toBeDisabled()
    expect(screen.getByLabelText('备份密码')).toBeDisabled()
    expect(screen.getByLabelText('导入备份文件')).toBeDisabled()
    expect(screen.getByRole('button', { name: '清空本机聊天与记忆' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '清空本机聊天与记忆' }))
    expect(clearAllData).not.toHaveBeenCalled()
    await act(async () => { pending.resolve(); await pending.promise })
    expect(exportData).toHaveBeenCalledTimes(1)
    expect(encryptBackup).toHaveBeenCalledExactlyOnceWith(rawBackup, 'secret')
    expect(createObjectURL).toHaveBeenCalledExactlyOnceWith(expect.any(Blob))
    const blob = createObjectURL.mock.calls[0][0] as Blob
    expect(blob.type).toBe('application/json')
    expect(blob.size).toBe(new Blob([encryptedBackup]).size)
    const anchor = vi.mocked(HTMLAnchorElement.prototype.click).mock.contexts[0] as HTMLAnchorElement
    expect(anchor.href).toBe('blob:encrypted-backup')
    expect(anchor.download).toMatch(/^aily-backup-\d{4}-\d{2}-\d{2}\.json$/)
    expect(anchor).not.toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('已发起加密备份下载')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(screen.getByLabelText('备份密码')).toHaveValue('')
    expect(screen.getByRole('region', { name: '本机聊天与记忆' })).toHaveAttribute('aria-busy', 'false')
    expect(revokeObjectURL).not.toHaveBeenCalled()
    act(() => vi.advanceTimersByTime(1000))
    expect(revokeObjectURL).toHaveBeenCalledExactlyOnceWith('blob:encrypted-backup')
    expect(onImported).not.toHaveBeenCalled()
    expect(onCleared).not.toHaveBeenCalled()
  })

  it('requires import confirmation and cancels without reading or replacing data', () => {
    const { beforeDataChange, onImported } = setup()
    expect(screen.getByRole('button', { name: '导入并替换本机数据' })).toBeDisabled()
    const { text } = chooseFile()
    requestImport()
    expect(screen.getByRole('group', { name: '确认导入备份' })).toHaveTextContent('此操作无法撤销')
    expect(screen.getByRole('button', { name: '导出加密备份' })).toBeDisabled()
    expect(text).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect(screen.queryByRole('group', { name: '确认导入备份' })).not.toBeInTheDocument()
    expect(screen.getByText(/已选择：saved-backup.json/)).toBeInTheDocument()
    expect(beforeDataChange).not.toHaveBeenCalled()
    expect(decryptBackup).not.toHaveBeenCalled()
    expect(importData).not.toHaveBeenCalled()
    expect(onImported).not.toHaveBeenCalled()
  })

  it('retries a wrong password using the same file and imports only after decryption and local writes', async () => {
    vi.mocked(decryptBackup).mockRejectedValueOnce(new Error('密码错误或备份文件已损坏'))
    const pending = deferred()
    const { beforeDataChange, onImported, onCleared } = setup(vi.fn().mockReturnValue(pending.promise))
    const { file, text } = chooseFile()
    password('wrong-password')
    requestImport(); confirmImport()
    expect(await screen.findByRole('alert')).toHaveTextContent('密码错误或备份文件已损坏')
    expect(beforeDataChange).not.toHaveBeenCalled()
    expect(importData).not.toHaveBeenCalled()
    expect(screen.getByRole('group', { name: '确认导入备份' })).toBeInTheDocument()
    expect(screen.getByLabelText('备份密码')).toHaveValue('wrong-password')
    expect((screen.getByLabelText('导入备份文件') as HTMLInputElement).files?.[0]).toBe(file)
    password('correct-password'); confirmImport()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '正在处理…' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '正在处理…' }))
    await waitFor(() => expect(beforeDataChange).toHaveBeenCalledTimes(1))
    expect(decryptBackup).toHaveBeenNthCalledWith(1, encryptedBackup, 'wrong-password')
    expect(decryptBackup).toHaveBeenNthCalledWith(2, encryptedBackup, 'correct-password')
    expect(text).toHaveBeenCalledTimes(2)
    expect(importData).not.toHaveBeenCalled()
    await act(async () => { pending.resolve(); await pending.promise })
    expect(await screen.findByRole('status')).toHaveTextContent('备份已导入，本机资料已更新')
    expect(importData).toHaveBeenCalledExactlyOnceWith(rawBackup)
    expect(onImported).toHaveBeenCalledExactlyOnceWith(importedData)
    expect(onCleared).not.toHaveBeenCalled()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(screen.queryByRole('group', { name: /确认导入备份|确认清空聊天/ })).not.toBeInTheDocument()
    expect(screen.queryByText(/已选择：/)).not.toBeInTheDocument()
    expect(screen.getByLabelText('导入备份文件')).toHaveValue('')
    expect(screen.getByLabelText('备份密码')).toHaveValue('')
    expect(screen.getByRole('button', { name: '导入并替换本机数据' })).toBeDisabled()
  })

  it('allows a legacy unencrypted backup to be imported with an empty password', async () => {
    const { onImported } = setup()
    chooseFile(rawBackup); requestImport(); confirmImport()
    expect(await screen.findByRole('status')).toHaveTextContent('备份已导入')
    expect(decryptBackup).toHaveBeenCalledExactlyOnceWith(rawBackup, '')
    expect(onImported).toHaveBeenCalledExactlyOnceWith(importedData)
  })

  it('cancels clear, then requires explicit confirmation and waits for writes before deletion', async () => {
    const pending = deferred()
    const { beforeDataChange, onCleared, onImported } = setup(vi.fn().mockReturnValue(pending.promise))
    chooseFile(); password('secret')
    requestClear()
    expect(screen.getByRole('group', { name: '确认清空聊天' })).toHaveTextContent('演示钱包不变')
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect(beforeDataChange).not.toHaveBeenCalled()
    expect(clearAllData).not.toHaveBeenCalled()
    expect(onCleared).not.toHaveBeenCalled()
    requestClear(); confirmClear()
    fireEvent.click(screen.getByRole('button', { name: '正在处理…' }))
    expect(beforeDataChange).toHaveBeenCalledTimes(1)
    expect(clearAllData).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: '取消' })).toBeDisabled()
    await act(async () => { pending.resolve(); await pending.promise })
    expect(await screen.findByRole('status')).toHaveTextContent('本机聊天、记忆与相关设置已清空')
    expect(clearAllData).toHaveBeenCalledTimes(1)
    expect(onCleared).toHaveBeenCalledTimes(1)
    expect(onImported).not.toHaveBeenCalled()
    expect(screen.queryByRole('group', { name: /确认导入备份|确认清空聊天/ })).not.toBeInTheDocument()
    expect(screen.queryByText(/已选择：/)).not.toBeInTheDocument()
    expect(screen.getByLabelText('备份密码')).toHaveValue('')
  })

  it.each(['export', 'import', 'clear'] as const)('does not perform %s when beforeDataChange fails', async operation => {
    const { beforeDataChange, onImported, onCleared } = setup(vi.fn().mockRejectedValue(new Error('等待本机写入失败')))
    password('secret')
    if (operation === 'export') fireEvent.click(screen.getByRole('button', { name: '导出加密备份' }))
    if (operation === 'import') { chooseFile(); requestImport(); confirmImport() }
    if (operation === 'clear') { requestClear(); confirmClear() }
    expect(await screen.findByRole('alert')).toHaveTextContent('等待本机写入失败')
    expect(beforeDataChange).toHaveBeenCalledTimes(1)
    expect(exportData).not.toHaveBeenCalled()
    expect(encryptBackup).not.toHaveBeenCalled()
    expect(createObjectURL).not.toHaveBeenCalled()
    expect(importData).not.toHaveBeenCalled()
    expect(clearAllData).not.toHaveBeenCalled()
    expect(onImported).not.toHaveBeenCalled()
    expect(onCleared).not.toHaveBeenCalled()
    expect(screen.getByLabelText('备份密码')).toHaveValue('secret')
    expect(screen.getByLabelText('备份密码')).toBeEnabled()
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    if (operation === 'import') {
      expect(decryptBackup).toHaveBeenCalledExactlyOnceWith(encryptedBackup, 'secret')
      expect(screen.getByText(/已选择：saved-backup.json/)).toBeInTheDocument()
      expect(screen.getByRole('button', { name: '确认替换' })).toBeEnabled()
    }
    if (operation === 'clear') expect(screen.getByRole('button', { name: '确认清空' })).toBeEnabled()
  })

  it('keeps error notices separate from success and clears stale feedback for a new action/file', async () => {
    setup()
    fireEvent.click(screen.getByRole('button', { name: '导出加密备份' }))
    expect(await screen.findByRole('alert')).toHaveClass('is-error')
    chooseFile()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    requestImport(); confirmImport()
    expect(await screen.findByRole('status')).not.toHaveClass('is-error')
    requestClear()
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    vi.mocked(clearAllData).mockRejectedValueOnce(new Error('无法清空本机数据'))
    confirmClear()
    expect(await screen.findByRole('alert')).toHaveTextContent('无法清空本机数据')
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    confirmClear()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(await screen.findByRole('status')).toHaveTextContent('已清空')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })
})
