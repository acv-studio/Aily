import { wardrobePhotoDb, WARDROBE_KEY, type WardrobeItem } from './wardrobeData'
const old: WardrobeItem[] = [{ id: 'top', name: 'Mint jacket', category: '上装', color: 'Mint', season: '四季', extra: { retained: true } }, { id: 'pants', name: 'Lavender pants', category: '下装', color: 'Lavender', season: '春秋' }, { id: 'shoes', name: 'Old shoes', category: '鞋包', color: '', season: '四季' }]
