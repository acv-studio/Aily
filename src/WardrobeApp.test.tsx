it('adds a real local photo, keeps it across reopen and does not put bytes into metadata', async () => {
  render(<WardrobeApp locale="en" />); const dialog = openAdd()
  fireEvent.change(within(dialog).getByLabelText('Clothing name'), { target: { value: 'White shirt' } })
  const file = new NodeFile(['photo bytes'], 'shirt.png', { type: 'image/png' })
  fireEvent.change(screen.getByLabelText('Choose clothing photo'), { target: { files: [file] } })
  fireEvent.click(screen.getByRole('button', { name: 'Add to wardrobe' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  const item = stored()[0]
  expect(item).toMatchObject({ name: 'White shirt', category: '上装' }); expect(item.photoId).toBeTruthy()
  expect(localStorage.getItem(WARDROBE_KEY)).not.toContain('photo bytes')
  expect((await wardrobePhotoDb.photos.get(item.photoId!))?.blob.size).toBe(file.size)
  cleanup(); render(<WardrobeApp locale="en" />)
  expect(await screen.findByRole('img', { name: 'White shirt' })).toBeInTheDocument()
})
