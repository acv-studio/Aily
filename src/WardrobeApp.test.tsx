it('preserves a library editor draft after external changes and confirms before discarding', async () => {
  localStorage.setItem(WARDROBE_KEY, JSON.stringify(old)); render(<WardrobeApp locale="en" />)
  fireEvent.click(screen.getByRole('button', { name: 'Categories' }))
  fireEvent.click(screen.getByRole('button', { name: 'Edit clothing: Mint jacket' }))
  fireEvent.change(screen.getByLabelText('Clothing name'), { target: { value: 'Unsaved draft' } })
  const updated = old.map(item => item.id === 'top' ? { ...item, name: 'External change' } : item)
  localStorage.setItem(WARDROBE_KEY, JSON.stringify(updated))
  fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('your form draft will be kept')
  expect(screen.getByLabelText('Clothing name')).toHaveValue('Unsaved draft'); expect(stored()).toEqual(updated)
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Reload data' }))
  fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
  expect(screen.getByText('This item changed. Keep your draft, close and reload.')).toBeInTheDocument()
  expect(stored()).toEqual(updated)
  vi.mocked(window.confirm).mockReturnValueOnce(false)
  fireEvent.click(screen.getByRole('button', { name: 'Close clothing editor' }))
  expect(screen.getByLabelText('Clothing name')).toHaveValue('Unsaved draft')
  fireEvent.click(screen.getByRole('button', { name: 'Close clothing editor' }))
  expect(screen.queryByRole('dialog')).toBeNull(); expect(stored()).toEqual(updated)
})
