import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import App from './App'
import { db, loadLocalData, saveSetting } from './db'
import { defaultSplashSettings, saveSplashSettings } from './characterPresence'
import * as presence from './characterPresence'
import { defaultOnboardingProfile } from './onboarding'
import { acceptSafetyConsent } from './privacy'

beforeEach(async () => { localStorage.clear(); sessionStorage.clear(); await db.delete(); await db.open(); vi.setSystemTime(new Date(2026, 10, 3, 19)); Element.prototype.scrollIntoView = vi.fn() })
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks() })
async function returning() { acceptSafetyConsent(); await saveSetting('onboarded', true); await saveSetting('selected', 'lu') }

describe('character splash entry and settings', () => {
  it('skips first onboarding completion and preserves its role as primary on the next open', async () => {
    const app = render(<App />)
    await screen.findByRole('button', { name: /遇见 TA/ })
    fireEvent.click(screen.getByLabelText('我已年满 18 周岁'))
    fireEvent.click(screen.getByLabelText('我理解 AI 身份与数据说明'))
    fireEvent.click(screen.getByRole('button', { name: /遇见 TA/ }))
    fireEvent.click(screen.getByRole('button', { name: /陈奕恒/ }))
    fireEvent.click(screen.getByRole('button', { name: /开始我们的故事/ }))
    for (let step = 0; step < 5; step++) fireEvent.click(screen.getByRole('button', { name: '继续' }))
    fireEvent.click(screen.getByRole('button', { name: '发送试聊' }))
    fireEvent.click(screen.getByRole('button', { name: '称呼没问题，继续' }))
    fireEvent.click(screen.getByRole('button', { name: '完成引导' }))
    await screen.findByRole('button', { name: '消息' })
    expect(screen.queryByRole('button', { name: '跳过，进入消息' })).not.toBeInTheDocument()
    app.unmount()
    render(<App />)
    expect(await screen.findByRole('button', { name: '与陈奕恒继续聊天' })).toBeInTheDocument()
  })
  it('migrates the first onboarding choice rather than the last conversation', async () => {
    await returning()
    await saveSetting('onboardingProfile', defaultOnboardingProfile('chen'))
    render(<App />)
    expect(await screen.findByRole('button', { name: '与陈奕恒继续聊天' })).toBeInTheDocument()
  })
  it('uses an independent primary and enters its existing conversation without exposing it on splash', async () => {
    await returning()
    await db.messages.put({ characterId: 'gu', id: 1, from: 'user', text: '健康私密内容', time: '19:00' })
    await saveSplashSettings(defaultSplashSettings('gu'))
    render(<App />)
    fireEvent.click(await screen.findByRole('button', { name: '与顾辰泽继续聊天' }))
    expect(await screen.findByText('健康私密内容')).toBeInTheDocument()
    expect((await loadLocalData()).settings.selected).toBe('gu')
    expect(await db.messages.count()).toBe(1)
  })
  it('keeps private history off splash and shows the same safe status on home after skip', async () => {
    await returning()
    await db.messages.put({ characterId: 'lu', id: 1, from: 'user', text: '不能在屏保出现', time: '19:00' })
    render(<App />)
    const skip = await screen.findByRole('button', { name: '跳过，进入消息' })
    expect(screen.queryByText('不能在屏保出现')).not.toBeInTheDocument()
    expect(screen.getByText('正在练新菜')).toBeInTheDocument()
    fireEvent.click(skip)
    expect(await screen.findByText('正在练新菜')).toBeInTheDocument()
  })
  it('persists disabled/static/non-personalized preferences and starts on primary home without splash', async () => {
    await returning(); render(<App />)
    fireEvent.click(await screen.findByRole('button', { name: '跳过，进入消息' }))
    fireEvent.click(screen.getByRole('button', { name: '我的' }))
    fireEvent.change(screen.getByLabelText('主角色'), { target: { value: 'chen' } })
    fireEvent.click(screen.getByRole('checkbox', { name: '再次打开时展示屏保' }))
    fireEvent.click(screen.getByRole('checkbox', { name: '按本地时间展示角色日程' }))
    fireEvent.click(screen.getByRole('checkbox', { name: '静态画面（关闭动效）' }))
    fireEvent.click(screen.getByRole('button', { name: '保存主角色与屏保' }))
    await screen.findByRole('status')
    cleanup(); render(<App />)
    await screen.findByRole('button', { name: '消息' })
    expect(screen.queryByRole('button', { name: '跳过，进入消息' })).not.toBeInTheDocument()
    expect(screen.getByText('在这里等你')).toBeInTheDocument()
    expect(screen.getAllByText('陈奕恒')).toHaveLength(2)
  })
  it('safely skips splash and time personalization when preferences cannot be read', async () => {
    await returning()
    vi.spyOn(presence, 'loadSplashSettings').mockRejectedValue(new Error('unavailable'))
    render(<App />)
    await screen.findByRole('button', { name: '消息' })
    expect(screen.queryByRole('button', { name: '跳过，进入消息' })).not.toBeInTheDocument()
    expect(screen.getByText('在这里等你')).toBeInTheDocument()
  })
  it('refreshes an already-open scene to current time after returning from background', async () => {
    await returning(); render(<App />)
    await screen.findByRole('button', { name: '跳过，进入消息' })
    expect(screen.getByText('正在练新菜')).toBeInTheDocument()
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
    fireEvent(document, new Event('visibilitychange'))
    vi.setSystemTime(new Date(2026, 10, 4, 8))
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
    fireEvent(document, new Event('visibilitychange'))
    expect(await screen.findByText('正在准备早餐')).toBeInTheDocument()
  })
  it('shows again after a minute away from home, but never replaces active chat', async () => {
    await returning(); render(<App />)
    fireEvent.click(await screen.findByRole('button', { name: '跳过，进入消息' }))
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
    fireEvent(document, new Event('visibilitychange'))
    vi.setSystemTime(new Date(2026, 10, 3, 19, 2))
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
    fireEvent(document, new Event('visibilitychange'))
    await screen.findByRole('button', { name: '与陆听澜继续聊天' })
    fireEvent.click(screen.getByRole('button', { name: '与陆听澜继续聊天' }))
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('hidden')
    fireEvent(document, new Event('visibilitychange'))
    vi.setSystemTime(new Date(2026, 10, 3, 19, 4))
    vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
    fireEvent(document, new Event('visibilitychange'))
    await waitFor(() => expect(screen.queryByRole('button', { name: '跳过，进入消息' })).not.toBeInTheDocument())
    vi.restoreAllMocks()
  })
})
