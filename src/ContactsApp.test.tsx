import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import ContactsApp, { contactEmailHref, contactPhoneHref } from './ContactsApp'
const KEY = 'aily-desktop-contacts'
const contact = { id: 'legacy', name: 'Lin', phone: '+1 (202) 555-0100', email: 'lin@example.com', custom: { retained: true } }
const change = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } })
beforeEach(() => localStorage.clear())
afterEach(() => { cleanup(); vi.restoreAllMocks() })

it('reads legacy schema without writes, searches and edits without dropping unknown data', () => {
  const raw = JSON.stringify([contact]); localStorage.setItem(KEY, raw)
  const writes = vi.spyOn(Storage.prototype, 'setItem')
  const view = render(<ContactsApp locale="en" />)
  expect(writes).not.toHaveBeenCalled()
  expect(screen.getByText(/does not access phone or system contacts/)).toBeInTheDocument()
  expect(screen.getByRole('link', { name: 'Call: Lin' })).toHaveAttribute('href', 'tel:+12025550100')
  expect(screen.getByRole('link', { name: 'Email: Lin' })).toHaveAttribute('href', 'mailto:lin%40example.com')
  change('Search contacts', 'missing'); expect(screen.queryByText('Lin')).toBeNull()
  change('Search contacts', 'EXAMPLE'); expect(screen.getByText('Lin')).toBeInTheDocument()
  change('Search contacts', '')
  fireEvent.click(screen.getByRole('button', { name: 'Edit contact: Lin' }))
  change('Name', 'Linda'); fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)).toEqual([{ ...contact, name: 'Linda' }])
  view.unmount(); render(<ContactsApp locale="en" />)
  expect(screen.getByText('Linda')).toBeInTheDocument()
})

it('creates and edits optional groups while combining group, search and favorite filters', () => {
  localStorage.setItem(KEY, JSON.stringify([contact, { ...contact, id: 'friend', name: 'Maya', group: 'Friends', favorite: true }]))
  render(<ContactsApp locale="en" />)
  change('Name', 'Alex'); change('Group (optional)', ' Family ')
  fireEvent.click(screen.getByRole('button', { name: 'Add contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)[0].group).toBe('Family')
  expect(screen.getByText('Group: Family')).toBeInTheDocument()
  change('Filter by group', 'group:Family')
  expect(screen.getByText('Alex')).toBeInTheDocument()
  expect(screen.queryByText('Lin')).toBeNull()
  change('Filter by group', 'ungrouped')
  expect(screen.getByText('Lin')).toBeInTheDocument()
  expect(screen.queryByText('Alex')).toBeNull()
  change('Filter by group', 'group:Friends'); fireEvent.click(screen.getByRole('button', { name: 'Favorites only' }))
  change('Search contacts', 'maya'); expect(screen.getByText('Maya')).toBeInTheDocument()
  change('Search contacts', 'missing'); expect(screen.getByText('No matching contacts.')).toBeInTheDocument()
  change('Search contacts', ''); fireEvent.click(screen.getByRole('button', { name: 'Favorites only' })); change('Filter by group', '')
  fireEvent.click(screen.getByRole('button', { name: 'Edit contact: Alex' }))
  expect(screen.getByLabelText('Group (optional)')).toHaveValue('Family')
  change('Group (optional)', 'Work'); fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)[0].group).toBe('Work')
  fireEvent.click(screen.getByRole('button', { name: 'Edit contact: Alex' }))
  change('Group (optional)', ''); fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)[0]).not.toHaveProperty('group')
  expect(JSON.parse(localStorage.getItem(KEY)!)[1]).toEqual(contact)
})

it('loads legacy records with no group without adding fields and preserves unknown group metadata', () => {
  const unknown = { ...contact, id: 'unknown', name: 'Unknown', group: { previousMetadata: true } }
  localStorage.setItem(KEY, JSON.stringify([contact, unknown]))
  const writes = vi.spyOn(Storage.prototype, 'setItem')
  render(<ContactsApp locale="en" />)
  expect(writes).not.toHaveBeenCalled()
  change('Filter by group', 'ungrouped')
  expect(screen.getByText('Lin')).toBeInTheDocument()
  expect(screen.getByText('Unknown')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Edit contact: Unknown' }))
  expect(screen.getByLabelText('Group (optional)')).toHaveValue('')
  change('Name', 'Changed'); fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)).toEqual([contact, { ...unknown, name: 'Changed' }])
})

it('supports persisted favorites while retaining the original contact fields', () => {
  localStorage.setItem(KEY, JSON.stringify([contact]))
  render(<ContactsApp locale="en" />)
  fireEvent.click(screen.getByRole('button', { name: 'Favorites only' }))
  expect(screen.queryByText('Lin')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Favorites only' }))
  fireEvent.click(screen.getByRole('button', { name: 'Favorite contact: Lin' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)[0]).toEqual({ ...contact, favorite: true })
  fireEvent.click(screen.getByRole('button', { name: 'Favorites only' }))
  expect(screen.getByText('Lin')).toBeInTheDocument()
})

it('keeps corrupt data untouched and permits explicit retry after recovery', () => {
  localStorage.setItem(KEY, '{broken')
  render(<ContactsApp locale="en" />)
  expect(screen.getByRole('button', { name: 'Add contact' })).toBeDisabled()
  expect(localStorage.getItem(KEY)).toBe('{broken')
  localStorage.setItem(KEY, JSON.stringify([contact]))
  fireEvent.click(screen.getByRole('button', { name: 'Retry loading' }))
  expect(screen.getByText('Lin')).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Add contact' })).toBeEnabled()
})

it('blocks stale updates, preserves the draft and loads external records before retry', () => {
  render(<ContactsApp locale="en" />)
  change('Name', 'Draft'); localStorage.setItem(KEY, JSON.stringify([contact]))
  fireEvent.click(screen.getByRole('button', { name: 'Add contact' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Local data changed')
  expect(JSON.parse(localStorage.getItem(KEY)!)).toEqual([contact])
  expect(screen.getByLabelText('Name')).toHaveValue('Draft')
  fireEvent.click(screen.getByRole('button', { name: 'Reload data' }))
  expect(screen.getByText('Lin')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Add contact' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)).toHaveLength(2)
})

it('refuses to apply an old edit draft over a reloaded changed contact', () => {
  localStorage.setItem(KEY, JSON.stringify([contact])); render(<ContactsApp locale="en" />)
  fireEvent.click(screen.getByRole('button', { name: 'Edit contact: Lin' })); change('Name', 'Draft')
  localStorage.setItem(KEY, JSON.stringify([{ ...contact, name: 'External' }]))
  fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  fireEvent.click(screen.getByRole('button', { name: 'Reload data' }))
  fireEvent.click(screen.getByRole('button', { name: 'Save contact' }))
  expect(screen.getByRole('alert')).toHaveTextContent('This contact has changed')
  expect(JSON.parse(localStorage.getItem(KEY)!)[0].name).toBe('External')
})

it('retains draft and original records if a write fails', () => {
  localStorage.setItem(KEY, JSON.stringify([contact])); render(<ContactsApp locale="en" />)
  change('Name', 'Draft')
  vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
  fireEvent.click(screen.getByRole('button', { name: 'Add contact' }))
  expect(screen.getByRole('alert')).toHaveTextContent('existing data is unchanged')
  expect(screen.getByLabelText('Name')).toHaveValue('Draft')
  expect(JSON.parse(localStorage.getItem(KEY)!)).toEqual([contact])
})

it('adds and deletes contacts using the original array schema', () => {
  render(<ContactsApp locale="zh-CN" />)
  change('姓名', '小林'); change('电话', '123456'); change('邮箱', 'lin@example.com')
  fireEvent.click(screen.getByRole('button', { name: '添加联系人' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)[0]).toMatchObject({ id: expect.any(String), name: '小林', phone: '123456', email: 'lin@example.com' })
  fireEvent.click(screen.getByRole('button', { name: '删除联系人：小林' }))
  expect(JSON.parse(localStorage.getItem(KEY)!)).toEqual([])
})

it('does not silently overwrite invalid-shaped or inaccessible storage', () => {
  const raw = JSON.stringify([{ id: 'bad', name: 'Bad', phone: 123, email: '' }])
  localStorage.setItem(KEY, raw)
  const view = render(<ContactsApp locale="en" />)
  expect(screen.getByRole('button', { name: 'Add contact' })).toBeDisabled()
  expect(localStorage.getItem(KEY)).toBe(raw)
  view.unmount()
  vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('SecurityError') })
  render(<ContactsApp locale="en" />)
  expect(screen.getByRole('alert')).toHaveTextContent('Changes are blocked to protect existing data')
})

it('shows unsafe stored values as text, never clickable links', () => {
  localStorage.setItem(KEY, JSON.stringify([{ ...contact, phone: 'javascript:alert(1)', email: 'x@example.com?body=bad' }]))
  render(<ContactsApp locale="en" />)
  expect(screen.queryByRole('link')).toBeNull()
  expect(screen.getByText('javascript:alert(1)')).toBeInTheDocument()
  for (const value of ['javascript:alert(1)', '123;456', '*123#', '123\n456']) expect(contactPhoneHref(value)).toBeUndefined()
  for (const value of ['javascript:alert(1)', 'a@b.com?subject=x', 'a@b.com\r\nBcc:x@y.com', 'a%0d@b.com']) expect(contactEmailHref(value)).toBeUndefined()
})
