import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import DesktopTools, { calculatePlumBlossom } from './DesktopTools'
import { setLocale } from './i18n'

beforeEach(() => { localStorage.clear(); setLocale('zh-CN') })
afterEach(() => { cleanup(); vi.restoreAllMocks() })
const change = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } })

describe('desktop local tools', () => {
  it('adds income/expense, updates totals, reloads and deletes ledger entries', () => {
    const view = render(<DesktopTools tool="ledger" onClose={vi.fn()} />)
    change('金额（元）', '12.30'); change('备注', '午餐'); fireEvent.click(screen.getByRole('button', { name: '添加记录' }))
    change('收支类型', 'income'); change('金额（元）', '100'); change('备注', '收入测试'); fireEvent.click(screen.getByRole('button', { name: '添加记录' }))
    expect(screen.getByText('¥87.70')).toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem('aily-desktop-ledger')!)).toHaveLength(2)
    view.unmount(); render(<DesktopTools tool="ledger" onClose={vi.fn()} />)
    expect(screen.getByText('午餐')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '删除记录：午餐' }))
    expect(screen.queryByText('午餐')).toBeNull()
    expect(JSON.parse(localStorage.getItem('aily-desktop-ledger')!)).toHaveLength(1)
  })
  it('stores and deletes user-defined contacts without system access', () => {
    render(<DesktopTools tool="contacts" onClose={vi.fn()} />)
    expect(screen.getByText(/不会读取手机或系统联系人/)).toBeInTheDocument()
    change('姓名', '小林'); change('电话', '123456'); change('邮箱', 'lin@example.com')
    fireEvent.click(screen.getByRole('button', { name: '添加联系人' }))
    expect(screen.getByText('lin@example.com')).toBeInTheDocument()
    expect(JSON.parse(localStorage.getItem('aily-desktop-contacts')!)[0]).toMatchObject({ name: '小林', phone: '123456' })
    fireEvent.click(screen.getByRole('button', { name: '删除联系人：小林' }))
    expect(JSON.parse(localStorage.getItem('aily-desktop-contacts')!)).toEqual([])
  })
  it('saves dated diary entries, keeps data on tool switches and deletes entries', () => {
    const view = render(<DesktopTools tool="diary" onClose={vi.fn()} />)
    change('日记日期', '2026-11-04'); change('今天想记下什么', '今天走了很远。')
    fireEvent.click(screen.getByRole('button', { name: '保存日记' }))
    expect(screen.getByText('今天走了很远。')).toBeInTheDocument()
    view.rerender(<DesktopTools tool="contacts" onClose={vi.fn()} />)
    expect(screen.getByRole('heading', { name: '通讯录' })).toBeInTheDocument()
    expect(screen.queryByText('今天走了很远。')).toBeNull()
    view.rerender(<DesktopTools tool="diary" onClose={vi.fn()} />)
    expect(screen.getByText('今天走了很远。')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '删除日记：2026-11-04' }))
    expect(JSON.parse(localStorage.getItem('aily-desktop-diary')!)).toEqual([])
  })
  it('protects corrupt stored data from overwrites and offers retry', () => {
    localStorage.setItem('aily-desktop-ledger', '{invalid')
    render(<DesktopTools tool="ledger" onClose={vi.fn()} />)
    expect(screen.getByRole('alert')).toHaveTextContent('本地数据读取失败')
    expect(screen.getByRole('button', { name: '添加记录' })).toBeDisabled()
    expect(localStorage.getItem('aily-desktop-ledger')).toBe('{invalid')
    localStorage.setItem('aily-desktop-ledger', '[]')
    fireEvent.click(screen.getByRole('button', { name: '重试读取' }))
    expect(screen.getByRole('button', { name: '添加记录' })).toBeEnabled()
  })
  it('rejects invalid stored record shapes', () => {
    localStorage.setItem('aily-desktop-diary', JSON.stringify([{ id: 'bad', date: 'invalid', text: 'test' }]))
    render(<DesktopTools tool="diary" onClose={vi.fn()} />)
    expect(screen.getByRole('button', { name: '保存日记' })).toBeDisabled()
    expect(screen.getByRole('alert')).toBeInTheDocument()
  })
  it('shows write failures and retains input and previous records', () => {
    render(<DesktopTools tool="contacts" onClose={vi.fn()} />)
    change('姓名', '未保存')
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('QuotaExceededError') })
    fireEvent.click(screen.getByRole('button', { name: '添加联系人' }))
    expect(screen.getByRole('alert')).toHaveTextContent('本次修改未保存')
    expect(screen.getByLabelText('姓名')).toHaveValue('未保存')
    expect(screen.queryByText('未保存')).toBeNull()
  })
  it('blocks stale writes from another tab and reloads while retaining the draft', () => {
    render(<DesktopTools tool="contacts" onClose={vi.fn()} />)
    change('姓名', '我的草稿')
    const other = [{ id: 'other', name: '另一页面', phone: '', email: '' }]
    localStorage.setItem('aily-desktop-contacts', JSON.stringify(other))
    fireEvent.click(screen.getByRole('button', { name: '添加联系人' }))
    expect(screen.getByRole('alert')).toHaveTextContent('本地数据已在其他页面或操作中更改')
    expect(JSON.parse(localStorage.getItem('aily-desktop-contacts')!)).toEqual(other)
    expect(screen.getByLabelText('姓名')).toHaveValue('我的草稿')
    expect(screen.getByRole('button', { name: '添加联系人' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '重新读取' }))
    expect(screen.getByText('另一页面')).toBeInTheDocument()
    expect(screen.getByLabelText('姓名')).toHaveValue('我的草稿')
    fireEvent.click(screen.getByRole('button', { name: '添加联系人' }))
    expect(JSON.parse(localStorage.getItem('aily-desktop-contacts')!)).toHaveLength(2)
  })
  it('preserves existing diary entries when deleting cannot be persisted', () => {
    localStorage.setItem('aily-desktop-diary', JSON.stringify([{ id: 'saved', date: '2026-11-04', text: '保留这篇' }]))
    render(<DesktopTools tool="diary" onClose={vi.fn()} />)
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('Storage denied') })
    fireEvent.click(screen.getByRole('button', { name: '删除日记：2026-11-04' }))
    expect(screen.getByText('保留这篇')).toBeInTheDocument()
    expect(screen.getByRole('alert')).toHaveTextContent('原数据保持不变')
    expect(JSON.parse(localStorage.getItem('aily-desktop-diary')!)).toHaveLength(1)
  })
  it('shows inaccessible storage rather than silently falling back', () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('SecurityError') })
    render(<DesktopTools tool="diary" onClose={vi.fn()} />)
    expect(screen.getByRole('alert')).toHaveTextContent('本地数据读取失败')
  })
  it('traps keyboard focus, closes with Escape, and restores trigger focus', () => {
    const trigger = document.createElement('button'); document.body.appendChild(trigger); trigger.focus()
    const onClose = vi.fn()
    const view = render(<DesktopTools tool="contacts" onClose={onClose} />)
    expect(screen.getByRole('dialog')).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Tab' })
    expect(screen.getByRole('button', { name: '关闭工具' })).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Tab', shiftKey: true })
    expect(screen.getByRole('button', { name: '添加联系人' })).toHaveFocus()
    trigger.focus(); expect(screen.getByRole('dialog')).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Escape' }); expect(onClose).toHaveBeenCalledTimes(1)
    view.unmount(); expect(trigger).toHaveFocus(); trigger.remove()
  })
  it('uses bilingual copy without shared locale edits', () => {
    setLocale('en'); render(<DesktopTools tool="ledger" onClose={vi.fn()} />)
    expect(screen.getByRole('dialog', { name: 'Ledger' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Add entry' })).toBeInTheDocument()
    expect(screen.getByText(/not included in encrypted chat backups/)).toBeInTheDocument()
  })
})

describe('session-only media', () => {
  function urls() {
    Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:local-test') })
    Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
  }
  it('previews chosen images only and revokes on removal', () => {
    urls(); render(<DesktopTools tool="album" onClose={vi.fn()} />)
    expect(screen.queryByRole('img')).toBeNull()
    fireEvent.change(screen.getByLabelText('选择图片'), { target: { files: [new File(['image'], 'mine.png', { type: 'image/png' })] } })
    expect(screen.getByRole('img', { name: 'mine.png' })).toHaveAttribute('src', 'blob:local-test')
    fireEvent.click(screen.getByRole('button', { name: '移除：mine.png' }))
    expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:local-test')
    expect(screen.queryByRole('img')).toBeNull()
    expect(localStorage.getItem('aily-desktop-album')).toBeNull()
  })
  it('uses a real local audio player and revokes its URL on tool change', () => {
    urls(); const view = render(<DesktopTools tool="music" onClose={vi.fn()} />)
    fireEvent.change(screen.getByLabelText('选择音频'), { target: { files: [new File(['audio'], 'mine.mp3', { type: 'audio/mpeg' })] } })
    expect(screen.getByLabelText('mine.mp3')).toHaveAttribute('controls')
    expect(screen.getByLabelText('mine.mp3')).toHaveAttribute('src', 'blob:local-test')
    view.rerender(<DesktopTools tool="album" onClose={vi.fn()} />)
    expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:local-test')
    expect(localStorage.getItem('aily-desktop-music')).toBeNull()
  })
  it('reports unsupported selected file types', () => {
    urls(); render(<DesktopTools tool="album" onClose={vi.fn()} />)
    fireEvent.change(screen.getByLabelText('选择图片'), { target: { files: [new File(['txt'], 'notes.txt', { type: 'text/plain' })] } })
    expect(screen.getByRole('alert')).toHaveTextContent('部分文件无法打开')
    expect(URL.createObjectURL).not.toHaveBeenCalled()
  })
})

describe('deterministic cultural divination', () => {
  it('uses traditional trigram numbering, correct bottom-up moving line, and changed hexagram', () => {
    const result = calculatePlumBlossom(1, 1)
    expect(result).toMatchObject({ name: '乾', movingLine: 2, changedName: '同人', upper: { name: '乾' }, lower: { name: '乾' } })
    expect(calculatePlumBlossom(1, 1)).toEqual(result)
    expect(calculatePlumBlossom(8, 8)).toMatchObject({ name: '坤', movingLine: 4, changedName: '豫' })
    expect(() => calculatePlumBlossom(0, 1)).toThrow()
    expect(() => calculatePlumBlossom(1.5, 1)).toThrow()
  })
  it('renders result with entertainment-only warning and explains simplified time method', () => {
    render(<DesktopTools tool="divination" onClose={vi.fn()} />)
    expect(screen.getByText(/不提供财务、投资或健康建议/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '起卦' }))
    expect(screen.getByRole('heading', { name: '本卦 · 乾' })).toBeInTheDocument()
    change('起卦方式', 'time'); change('本地日期时间', '2026-11-04T12:00')
    fireEvent.click(screen.getByRole('button', { name: '起卦' }))
    expect(screen.getByText(/非农历法/)).toBeInTheDocument()
    expect(localStorage.getItem('aily-desktop-divination')).toBeNull()
  })
})
