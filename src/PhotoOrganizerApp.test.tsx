import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import PhotoOrganizerApp from './PhotoOrganizerApp'
import { addLibraryMedia, clearMediaLibrary, mediaDb } from './mediaLibrary'
import { photoSwipe, randomPhoto, type OrganizerPhoto } from './photoOrganizer'
import { listPhotos, getPhoto, deletePhotos, isPhotoOrganizerAvailable } from './nativePhotoOrganizer'
vi.mock('./nativePhotoOrganizer', () => ({ isPhotoOrganizerAvailable: vi.fn(() => false), listPhotos: vi.fn(), getPhoto: vi.fn(), deletePhotos: vi.fn() }))
beforeEach(async () => {
  await mediaDb.delete(); await mediaDb.open()
  vi.mocked(isPhotoOrganizerAvailable).mockReturnValue(false)
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:photo-preview') })
  Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
})
afterEach(async () => { cleanup(); vi.restoreAllMocks(); vi.clearAllMocks(); await mediaDb.delete() })
const seed = () => addLibraryMedia('album', ['a.png', 'b.png', 'c.png'].map(name => ({ name, blob: new Blob(['photo'], { type: 'image/png' }) })))
const startLatest = async () => { const button = await screen.findByRole('button', { name: '从最新开始' }); await waitFor(() => expect(button).toBeEnabled()); fireEvent.click(button); await waitFor(() => expect(document.querySelector('.organizer-page-review')).not.toBeNull()) }
const loadedPhoto = async () => {
  if (document.querySelector('.organizer-page-overview')) await startLatest()
  if (document.querySelector('.organizer-page-pending')) fireEvent.click((await screen.findAllByRole('button', { name: /^查看待删除照片/ }))[0])
  const image = await screen.findByRole('img'); fireEvent.load(image); return image
}
describe('photo organizer', () => {
  it('offers a visible back arrow on the overview and returns to Aily', () => {
    const onClose = vi.fn()
    render(<PhotoOrganizerApp locale="zh-CN" onClose={onClose}/>)
    const back = screen.getByRole('button', { name: '返回' })
    expect(back.querySelector('.lucide-chevron-left')).not.toBeNull()
    expect(back.querySelector('.lucide-leaf')).toBeNull()
    fireEvent.click(back)
    expect(onClose).toHaveBeenCalledOnce()
  })
  it('detects intentional swipes and rejects short or ambiguous diagonals', () => {
    expect(photoSwipe(0, -80)).toBe('pending'); expect(photoSwipe(0, 80)).toBe('keep')
    expect(photoSwipe(-80, 0)).toBe('next'); expect(photoSwipe(80, 0)).toBe('previous')
    expect(photoSwipe(50, 0)).toBeNull(); expect(photoSwipe(80, 80)).toBeNull()
  })
  it('picks another random photo without mutating chronological order', () => {
    const photos: OrganizerPhoto[] = ['a', 'b'].map(id => ({ id, name: id, createdAt: '', source: 'library' }))
    expect(randomPhoto(photos, 'a')?.id).toBe('b'); expect(photos[0].id).toBe('a'); expect(randomPhoto([])).toBeUndefined()
  })
  it('starts with the newest unreviewed photo and proceeds to the next newest', async () => {
    await seed(); const rows = await mediaDb.items.toArray()
    await mediaDb.items.bulkPut(rows.map((row, index) => ({ ...row, addedAt: `2026-02-${18 + index}T10:00:00.000Z` })))
    render(<PhotoOrganizerApp locale="zh-CN" />)
    const first = await loadedPhoto(); expect(first).toHaveAttribute('alt', rows[2].name)
    fireEvent.click(screen.getByRole('button', { name: '下一张' }))
    const older = await screen.findByRole('img', { name: rows[1].name }); fireEvent.load(older)
    fireEvent.click(screen.getByRole('button', { name: '上一张' }))
    const newest = await screen.findByRole('img', { name: rows[2].name }); fireEvent.load(newest)
    fireEvent.click(screen.getByRole('button', { name: '保留' }))
    await waitFor(async () => expect(await mediaDb.photoDecisions.get(`library:${rows[2].id}`)).toMatchObject({ status: 'keep' }))
    expect(await screen.findByRole('img', { name: rows[1].name })).toBeInTheDocument()
  })
  it('browses without marking, flags without deletion, and undoes a decision', async () => {
    await seed(); render(<PhotoOrganizerApp locale="zh-CN" />)
    const first = await loadedPhoto()
    const firstName = first.getAttribute('alt')
    fireEvent.click(screen.getByRole('button', { name: '下一张' }))
    expect((await loadedPhoto()).getAttribute('alt')).not.toBe(firstName)
    expect(await mediaDb.photoDecisions.count()).toBe(0)
    fireEvent.click(screen.getByRole('button', { name: '待删除' }))
    await waitFor(async () => expect((await mediaDb.photoDecisions.toArray())[0]?.status).toBe('pending'))
    expect(await mediaDb.items.count()).toBe(3)
    fireEvent.click(screen.getByRole('button', { name: '撤销上一次' }))
    await waitFor(async () => expect(await mediaDb.photoDecisions.count()).toBe(0))
  })
  it('supports swipe browsing, upward flagging and cancellation without a decision', async () => {
    class TestPointerEvent extends MouseEvent {
      pointerId = 1
      isPrimary = true
    }
    vi.stubGlobal('PointerEvent', TestPointerEvent)
    Object.defineProperty(HTMLElement.prototype, 'setPointerCapture', { configurable: true, value: vi.fn() })
    try {
      await seed(); render(<PhotoOrganizerApp locale="zh-CN" />); const first = await loadedPhoto()
      const name = first.getAttribute('alt'), area = screen.getByRole('group', { name: '照片手势区域' })
      fireEvent.pointerDown(area, { clientX: 160, clientY: 160, button: 0 })
      fireEvent.pointerUp(area, { clientX: 70, clientY: 160 })
      expect((await loadedPhoto()).getAttribute('alt')).not.toBe(name)
      expect(await mediaDb.photoDecisions.count()).toBe(0)
      fireEvent.pointerDown(area, { clientX: 160, clientY: 160, button: 0 })
      fireEvent.pointerCancel(area)
      fireEvent.pointerUp(area, { clientX: 160, clientY: 60 })
      expect(await mediaDb.photoDecisions.count()).toBe(0)
      fireEvent.pointerDown(area, { clientX: 160, clientY: 160, button: 0 })
      fireEvent.pointerUp(area, { clientX: 160, clientY: 60 })
      await waitFor(async () => expect((await mediaDb.photoDecisions.toArray())[0]?.status).toBe('pending'))
    } finally { vi.unstubAllGlobals(); Reflect.deleteProperty(HTMLElement.prototype, 'setPointerCapture') }
  })
  it('keeps review decisions after reopening and filters the pending list', async () => {
    await seed(); const view = render(<PhotoOrganizerApp locale="zh-CN" />); await loadedPhoto()
    fireEvent.click(screen.getByRole('button', { name: '待删除' }))
    await waitFor(async () => expect(await mediaDb.photoDecisions.count()).toBe(1))
    view.unmount(); render(<PhotoOrganizerApp locale="zh-CN" />)
    fireEvent.click(await screen.findByRole('button', { name: '待删除 1' })); await loadedPhoto()
    fireEvent.click(screen.getByRole('button', { name: '保留' }))
    await waitFor(async () => expect((await mediaDb.photoDecisions.toArray())[0]?.status).toBe('keep'))
    expect(await screen.findByText('暂无待删除照片')).toBeInTheDocument()
    await clearMediaLibrary(); expect(await mediaDb.photoDecisions.count()).toBe(0)
  })
  it('lists flagged photos, confirms deletion, and deletes only Aily pending copies', async () => {
    await seed()
    const rows = await mediaDb.items.toArray()
    await mediaDb.photoDecisions.bulkPut([{ id: `library:${rows[0].id}`, status: 'pending', updatedAt: '' }, { id: `library:${rows[1].id}`, status: 'keep', updatedAt: '' }])
    render(<PhotoOrganizerApp locale="zh-CN" />)
    fireEvent.click(await screen.findByRole('button', { name: '待删除 1' }))
    expect(await screen.findByRole('button', { name: `查看待删除照片：${rows[0].name}` })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '一键删除全部（1）' }))
    expect(screen.getByRole('alertdialog')).toHaveTextContent('只删除 Aily 本机相册中的导入副本')
    expect(await mediaDb.items.count()).toBe(3)
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect(await mediaDb.items.count()).toBe(3)
    fireEvent.click(screen.getByRole('button', { name: '一键删除全部（1）' }))
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    await waitFor(async () => expect(await mediaDb.items.count()).toBe(2))
    expect(await mediaDb.items.get(rows[0].id)).toBeUndefined()
    expect(await mediaDb.photoDecisions.get(`library:${rows[1].id}`)).toMatchObject({ status: 'keep' })
    expect(deletePhotos).not.toHaveBeenCalled()
  })
  it('keeps system flags when native deletion is cancelled, without a false success', async () => {
    vi.mocked(isPhotoOrganizerAvailable).mockReturnValue(true)
    vi.mocked(listPhotos).mockResolvedValue({ photos: [{ id: 'native-1', name: 'Photo 1', createdAt: '' }], limited: false })
    vi.mocked(getPhoto).mockResolvedValue({ url: 'data:image/jpeg;base64,AA==' })
    vi.mocked(deletePhotos).mockRejectedValue(Object.assign(new Error('Cancelled'), { code: 'CANCELLED' }))
    await mediaDb.photoDecisions.put({ id: 'native:native-1', status: 'pending', updatedAt: '' })
    render(<PhotoOrganizerApp locale="zh-CN" />)
    await startLatest()
    fireEvent.click(await screen.findByRole('button', { name: '待删除 1' }))
    fireEvent.click(screen.getByRole('button', { name: '一键删除全部（1）' }))
    expect(screen.getByRole('alertdialog')).toHaveTextContent('将删除系统相册中的原照片')
    expect(deletePhotos).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    await screen.findByText('已取消删除，照片和标记均保留。')
    expect(deletePhotos).toHaveBeenCalledExactlyOnceWith({ ids: ['native-1'] })
    expect(await mediaDb.photoDecisions.get('native:native-1')).toMatchObject({ status: 'pending' })
    expect(screen.getByRole('button', { name: '一键删除全部（1）' })).toBeInTheDocument()
  })
  it('rechecks changed decisions after confirmation, refusing a stale destructive action', async () => {
    await seed(); const row = (await mediaDb.items.toArray())[0]
    await mediaDb.photoDecisions.put({ id: `library:${row.id}`, status: 'pending', updatedAt: '' })
    render(<PhotoOrganizerApp locale="zh-CN" />)
    fireEvent.click(await screen.findByRole('button', { name: '待删除 1' }))
    fireEvent.click(screen.getByRole('button', { name: '一键删除全部（1）' }))
    await act(async () => { await mediaDb.photoDecisions.update(`library:${row.id}`, { status: 'keep' }) })
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('待删除标记已更改')
    expect(await mediaDb.items.count()).toBe(3)
  })
  it('shows an empty state without requesting system permissions', async () => {
    render(<PhotoOrganizerApp locale="en" />)
    expect(await screen.findByText('Choose photos to start reviewing')).toBeInTheDocument()
    expect(listPhotos).not.toHaveBeenCalled()
  })
  it('reads system photos only on request, handles limited access, and loads just the active image', async () => {
    vi.mocked(isPhotoOrganizerAvailable).mockReturnValue(true)
    vi.mocked(listPhotos).mockResolvedValue({ photos: [{ id: 'native-1', name: 'Photo 1', createdAt: '2026-01-01' }], limited: true })
    vi.mocked(getPhoto).mockResolvedValue({ url: 'data:image/jpeg;base64,AA==' })
    render(<PhotoOrganizerApp locale="zh-CN" />)
    expect(listPhotos).not.toHaveBeenCalled()
    await startLatest()
    await loadedPhoto()
    expect(screen.getByText(/有限授权/)).toBeInTheDocument()
    expect(getPhoto).toHaveBeenCalledWith({ id: 'native-1' })
    await waitFor(() => expect(screen.getByRole('button', { name: '保留' })).toBeEnabled())
    fireEvent.click(screen.getByRole('button', { name: '保留' }))
    await waitFor(async () => expect(await mediaDb.photoDecisions.get('native:native-1')).toMatchObject({ status: 'keep' }))
    expect(await mediaDb.items.count()).toBe(0)
  })
  it('does not show or mark the previous asset while a new native preview is pending', async () => {
    vi.mocked(isPhotoOrganizerAvailable).mockReturnValue(true)
    vi.mocked(listPhotos).mockResolvedValue({ photos: [{ id: 'new', name: 'Newest', createdAt: '2026-02-20' }, { id: 'old', name: 'Older', createdAt: '2026-02-19' }], limited: false })
    let finishOlder!: (result: { url: string }) => void
    const older = new Promise<{ url: string }>(resolve => { finishOlder = resolve })
    vi.mocked(getPhoto).mockImplementation(({ id }) => id === 'new' ? Promise.resolve({ url: 'data:image/jpeg;base64,NEW' }) : older)
    render(<PhotoOrganizerApp locale="zh-CN" />); await startLatest(); await loadedPhoto()
    expect(screen.getByRole('img')).toHaveAttribute('alt', 'Newest')
    fireEvent.click(screen.getByRole('button', { name: '下一张' }))
    await waitFor(() => expect(getPhoto).toHaveBeenCalledWith({ id: 'old' }))
    expect(screen.queryByRole('img')).toBeNull()
    expect(screen.getByText('正在读取照片…')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '待删除' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '保留' })).toBeDisabled()
    await act(async () => { finishOlder({ url: 'data:image/jpeg;base64,OLD' }) })
    const image = await screen.findByRole('img', { name: 'Older' }); fireEvent.load(image)
    expect(image).toHaveAttribute('src', 'data:image/jpeg;base64,OLD')
    expect(await mediaDb.photoDecisions.count()).toBe(0)
  })
  it('reports permission denial without changing the current photo library', async () => {
    await seed(); vi.mocked(isPhotoOrganizerAvailable).mockReturnValue(true)
    vi.mocked(listPhotos).mockRejectedValue(new Error('Photo access denied'))
    render(<PhotoOrganizerApp locale="en" />)
    fireEvent.click(screen.getByRole('button', { name: 'Organizer settings' }))
    fireEvent.click(screen.getByRole('button', { name: 'Read device Photos' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Photo access denied')
    expect(await mediaDb.items.count()).toBe(3)
  })
})
