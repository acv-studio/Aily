import { beforeEach, expect, it, vi } from 'vitest'
const mocks=vi.hoisted(()=>({native:true,platform:'ios',accessory:vi.fn(),listen:vi.fn(),handlers:new Map<string,(info?:{keyboardHeight:number})=>void>()}))
vi.mock('@capacitor/core',()=>({Capacitor:{isNativePlatform:()=>mocks.native,getPlatform:()=>mocks.platform}}))
vi.mock('@capacitor/keyboard',()=>({Keyboard:{setAccessoryBarVisible:mocks.accessory,addListener:mocks.listen}}))
beforeEach(()=>{vi.resetModules();mocks.native=true;mocks.platform='ios';mocks.accessory.mockReset().mockResolvedValue(undefined);mocks.handlers.clear();mocks.listen.mockReset().mockImplementation(async(name,handler)=>{mocks.handlers.set(name,handler);return{remove:async()=>{}}});delete document.documentElement.dataset.keyboardOpen})
it('hides the iPhone accessory bar and updates soft keyboard state only once',async()=>{
 const module=await import('./nativeKeyboard')
 await vi.waitFor(()=>expect(mocks.listen).toHaveBeenCalledTimes(4))
 expect(mocks.accessory).toHaveBeenCalledExactlyOnceWith({isVisible:false})
 await module.initializeNativeKeyboard()
 expect(mocks.accessory).toHaveBeenCalledTimes(1)
 mocks.handlers.get('keyboardWillShow')!({keyboardHeight:330});expect(document.documentElement.dataset.keyboardOpen).toBe('true')
 mocks.handlers.get('keyboardDidHide')!();expect(document.documentElement.dataset.keyboardOpen).toBe('false')
 mocks.handlers.get('keyboardDidShow')!({keyboardHeight:0});expect(document.documentElement.dataset.keyboardOpen).toBe('false')
})
it('publishes real occlusion height and retains pre-resize dimensions until hide',async()=>{
 vi.stubGlobal('innerHeight',874);vi.stubGlobal('innerWidth',402)
 const module=await import('./nativeKeyboard');await vi.waitFor(()=>expect(mocks.listen).toHaveBeenCalledTimes(4))
 const notify=vi.fn();const off=module.subscribeNativeKeyboard(notify)
 mocks.handlers.get('keyboardWillShow')!({keyboardHeight:376})
 expect(module.getNativeKeyboardState()).toEqual({height:376,fullHeight:874,width:402})
 vi.stubGlobal('innerHeight',498);mocks.handlers.get('keyboardDidShow')!({keyboardHeight:376})
 expect(module.getNativeKeyboardState().fullHeight).toBe(874)
 expect(document.documentElement.style.getPropertyValue('--native-keyboard-height')).toBe('376px')
 mocks.handlers.get('keyboardDidHide')!();expect(module.getNativeKeyboardState().height).toBe(0)
 expect(notify).toHaveBeenCalledTimes(3);off();mocks.handlers.get('keyboardDidHide')!();expect(notify).toHaveBeenCalledTimes(3)
 vi.unstubAllGlobals()
})
it('rejects delayed show after hide and accepts the next fresh willShow',async()=>{
 const module=await import('./nativeKeyboard');await vi.waitFor(()=>expect(mocks.listen).toHaveBeenCalledTimes(4))
 mocks.handlers.get('keyboardWillShow')!({keyboardHeight:330});mocks.handlers.get('keyboardWillHide')!();mocks.handlers.get('keyboardDidShow')!({keyboardHeight:330});expect(module.getNativeKeyboardState().height).toBe(0)
 mocks.handlers.get('keyboardWillShow')!({keyboardHeight:350});expect(module.getNativeKeyboardState().height).toBe(350)
 window.dispatchEvent(new Event('pagehide'));expect(module.getNativeKeyboardState().height).toBe(0)
})
it('uses an unknown baseline instead of double subtraction after rotation',async()=>{
 vi.stubGlobal('innerHeight',874);vi.stubGlobal('innerWidth',402)
 const module=await import('./nativeKeyboard');await vi.waitFor(()=>expect(mocks.listen).toHaveBeenCalledTimes(4))
 mocks.handlers.get('keyboardWillShow')!({keyboardHeight:376});vi.stubGlobal('innerWidth',874);vi.stubGlobal('innerHeight',186);mocks.handlers.get('keyboardDidShow')!({keyboardHeight:216});expect(module.getNativeKeyboardState().fullHeight).toBe(0);vi.unstubAllGlobals()
})
it.each(['web','android'])('does not call iOS keyboard APIs on %s',async platform=>{mocks.platform=platform;mocks.native=platform!=='web';const module=await import('./nativeKeyboard');await module.initializeNativeKeyboard();expect(mocks.accessory).not.toHaveBeenCalled();expect(mocks.listen).not.toHaveBeenCalled()})
