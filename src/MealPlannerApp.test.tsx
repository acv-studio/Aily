import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import MealPlannerApp from './MealPlannerApp'
import { defaultSettings, ingredients, planMeal } from './mealPlanner'
import type { MealSettings, PantryItem, WashRecord } from './mealPlanner'

const KEY = 'aily.ext.meal.v1'
const TODAY = '2026-11-07'
const config = (patch: Partial<MealSettings> = {}): MealSettings => ({ ...structuredClone(defaultSettings), dishCount: 2, ...patch })
const seed = (settings: MealSettings, history: WashRecord[] = []) => localStorage.setItem(KEY, JSON.stringify({ settings, history }))
const saved = (): { settings: MealSettings; history: WashRecord[] } => JSON.parse(localStorage.getItem(KEY)!)
const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
const change = (label: string | RegExp, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } })
const step = (name: string) => fireEvent.click(within(screen.getByRole('navigation')).getByRole('button', { name: new RegExp(`${name}$`) }))
const amount = (pantry: PantryItem[], id: string) => pantry.filter(p => p.ingredientId === id).reduce((n, p) => n + p.quantity, 0)
const stock = (): PantryItem[] => ingredients.map(i => ({ ingredientId: i.id, quantity: 10000 }))
const start = (settings = config(), history: WashRecord[] = []) => {
  seed(settings, history)
  const view = render(<MealPlannerApp locale="zh-CN" />)
  click('生成这餐')
  return { view, plan: planMeal(settings, 0, TODAY) }
}
const checkShopping = () => screen.getAllByRole('checkbox').forEach(box => { if (!(box as HTMLInputElement).checked && !(box as HTMLInputElement).disabled) fireEvent.click(box) })

beforeEach(() => {
  localStorage.clear()
  vi.useFakeTimers({ toFake: ['Date'] })
  vi.setSystemTime(new Date(`${TODAY}T12:00:00`))
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })

describe('meal planner real-engine workflow', () => {
  it('initially exposes five coherent steps, and later steps require a generated meal', () => {
    const writes = vi.spyOn(Storage.prototype, 'setItem')
    render(<MealPlannerApp locale="zh-CN" />)
    const nav = screen.getByRole('navigation', { name: '用餐步骤' })
    expect(within(nav).getAllByRole('button').map(b => b.textContent)).toEqual(['1吃什么', '2买菜', '3备菜', '4炒菜', '5谁洗碗'])
    expect(within(nav).getByRole('button', { name: /吃什么$/ })).toHaveAttribute('aria-current', 'step')
    for (const tab of ['买菜', '备菜', '炒菜', '谁洗碗']) {
      step(tab)
      expect(screen.getByRole('heading', { name: '先安排这一餐' })).toBeInTheDocument()
    }
    expect(writes).not.toHaveBeenCalled()
    expect(localStorage.getItem(KEY)).toBeNull()
  })

  it('renders actual default recipes, quantities, shortages and an affordable purchase estimate', () => {
    const settings = structuredClone(defaultSettings)
    const { plan } = start(settings)
    expect(plan.recipes).toHaveLength(settings.dishCount + 1)
    for (const r of plan.recipes) expect(screen.getByRole('heading', { name: r.recipe.title })).toBeInTheDocument()
    expect(screen.getByText(`还需采购约 ¥${plan.purchaseEstimate.toFixed(2)}`)).toBeInTheDocument()
    expect(screen.getByText(/预算内/)).toBeInTheDocument()
    step('买菜')
    expect(screen.getAllByRole('checkbox')).toHaveLength(plan.shopping.filter(s => s.toBuy > 0).length)
    for (const item of plan.shopping) {
      const checkbox = screen.getByRole('checkbox', { name: new RegExp(`${item.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')} · 缺`) })
      expect(checkbox.closest('label')).toHaveTextContent(`缺 ${item.toBuy}${item.unit}`)
      expect(checkbox.closest('label')).toHaveTextContent(`需要 ${item.required}${item.unit} · 已有 0${item.unit}`)
    }
  })

  it('uses available pantry stock with a zero budget and excludes expired stock', () => {
    const settings = config({ budget: 0, pantry: [...stock(), { ingredientId: 'rice', quantity: 900, expiresOn: '2026-11-06' }] })
    const { plan } = start(settings)
    expect(plan.purchaseEstimate).toBe(0)
    expect(screen.getByText(/预算内/)).toBeInTheDocument()
    expect(screen.getByText(/大米.*已过期/)).toBeInTheDocument()
    step('买菜')
    expect(screen.getByText('冰箱食材已够本餐，无需购买。')).toBeInTheDocument()
    expect(screen.queryByRole('checkbox')).toBeNull()
    expect(screen.getByRole('button', { name: '本餐采购已全部入库' })).toBeDisabled()
  })

  it('generating, changing menus, shopping/prep/cook checks and navigation never write data', () => {
    const settings = config()
    seed(settings)
    const before = localStorage.getItem(KEY)
    const writes = vi.spyOn(Storage.prototype, 'setItem')
    render(<MealPlannerApp locale="zh-CN" />)
    click('生成这餐')
    const first = planMeal(settings, 0, TODAY)
    click('换一套')
    const next = planMeal(settings, 1, TODAY)
    expect(next.id).not.toBe(first.id)
    for (const r of next.recipes) expect(screen.getByRole('heading', { name: r.recipe.title })).toBeInTheDocument()
    step('买菜'); checkShopping()
    step('备菜'); fireEvent.click(screen.getAllByRole('checkbox')[0])
    step('炒菜'); fireEvent.click(screen.getAllByRole('checkbox')[0])
    click('这餐已完成'); click('取消')
    step('谁洗碗'); change('本餐主厨', settings.members[0].id)
    expect(writes).not.toHaveBeenCalled()
    expect(localStorage.getItem(KEY)).toBe(before)
  })
})

