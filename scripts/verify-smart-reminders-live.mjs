import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

// Verify the user's existing server, using an isolated browser profile only.
const url = process.env.BASE_URL || 'http://127.0.0.1:4175/'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Shanghai', locale: 'zh-CN', colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(url)
  await page.getByRole('button', { name: '遇见 TA', exact: true }).waitFor()
  await page.evaluate(async () => {
    localStorage.setItem('aily.locale', 'zh-CN')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
    await new Promise((resolve, reject) => {
      const request = indexedDB.open('aily')
      request.onerror = () => reject(request.error)
      request.onsuccess = () => {
        const db = request.result, transaction = db.transaction('settings', 'readwrite')
        transaction.objectStore('settings').put({ key: 'onboarded', value: true })
        transaction.oncomplete = () => { db.close(); resolve() }
        transaction.onerror = () => { db.close(); reject(transaction.error) }
      }
    })
  })
  await page.reload()
  const nav = page.getByRole('navigation')
  await nav.waitFor()
  assert.deepEqual(await nav.locator('button').allTextContents(), ['消息', '记忆', '提醒', '我的'])
  await nav.getByRole('button', { name: '提醒', exact: true }).click()
  await page.getByRole('button', { name: '智能提醒', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).waitFor()
  assert.equal(await page.getByText('还没有提醒，从一杯水开始吧。').count(), 1)
  await page.getByLabel('开启免打扰', { exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.reminder-check input').checked)
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).click()
  await page.getByText('提醒已保存', { exact: true }).waitFor()
  await page.getByRole('button', { name: '天气关怀', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).click()
  await page.getByText('提醒已保存', { exact: true }).waitFor()
  await page.getByLabel('当前温度（手动记录，°C）', { exact: true }).fill('5')
  await page.getByRole('button', { name: '更新温度', exact: true }).click()
  await page.getByText('天气记录已更新', { exact: true }).waitFor()
  await page.getByRole('button', { name: '心情关怀', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).click()
  await page.getByText('提醒已保存', { exact: true }).waitFor()
  await page.getByRole('button', { name: '心情低落', exact: true }).click()
  await page.getByText('心情记录已更新', { exact: true }).waitFor()
  assert.equal(await page.getByText('待处理', { exact: true }).count(), 2)
  await page.getByRole('button', { name: '地铁出行', exact: true }).click()
  await page.getByLabel('下车站点', { exact: true }).fill('人民广场')
  await page.getByLabel('出站口', { exact: true }).fill('A 口')
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).click()
  await page.getByText('提醒已保存', { exact: true }).waitFor()
  await page.getByLabel('刚做完或准备做的事', { exact: true }).fill('开完会')
  await page.getByRole('button', { name: '生成下一步建议', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '确认加入提醒', exact: true }).count(), 2)
  await page.getByRole('button', { name: '确认加入提醒', exact: true }).first().click()
  await page.getByText('下一步已加入提醒', { exact: true }).waitFor()
  await page.evaluate(async () => { window.scrollTo(0, 0); await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))) })
  await mkdir('docs/evidence/smart-reminders', { recursive: true })
  await page.screenshot({ path: 'docs/evidence/smart-reminders/live-4175-center.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.getByRole('button', { name: '← 返回', exact: true }).click()
  const banner = page.getByRole('status', { name: '到期提醒' })
  await banner.waitFor()
  assert.ok((await banner.textContent()).includes('待处理提醒: 2'))
  await banner.getByRole('button', { name: '稍后', exact: true }).click()
  await banner.getByText('待处理提醒: 1', { exact: true }).waitFor()
  await page.getByRole('navigation').getByRole('button', { name: '消息', exact: true }).click()
  await page.getByRole('button', { name: /^与.+聊天$/ }).click()
  await page.getByRole('textbox', { name: '发消息', exact: true }).waitFor()
  await page.getByRole('status', { name: '到期提醒' }).getByRole('button', { name: '查看', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).waitFor()
  await page.getByRole('button', { name: '← 返回', exact: true }).click()
  await page.getByRole('textbox', { name: '发消息', exact: true }).waitFor()
  await page.getByRole('button', { name: '返回消息', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: '我的', exact: true }).click()
  await page.getByRole('button', { name: '智能提醒', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).waitFor()
  assert.equal(await page.locator('.reminder-item').count(), 5)
  await page.reload()
  await page.getByRole('navigation').getByRole('button', { name: '提醒', exact: true }).click()
  await page.getByRole('button', { name: '智能提醒', exact: true }).click()
  await page.getByRole('button', { name: '确认添加提醒', exact: true }).waitFor()
  assert.equal(await page.locator('.reminder-item').count(), 5)
  await page.setViewportSize({ width: 320, height: 740 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  assert.equal(await page.locator('vite-error-overlay').count(), 0)
  assert.deepEqual(errors, [])
  console.log(`PASS ${url}: actual served smart reminders, four-tab navigation preserved, reminders/profile entries, save weather/mood/metro/plan, snooze banner, chat return, reload persistence and 390/320px layout; no browser errors.`)
} finally { await browser.close() }
