import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const browser = await chromium.launch()
const evidence = 'docs/evidence/chat-settings'
await mkdir(evidence, { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4175/')
  await page.evaluate(async () => {
    const { saveSetting } = await import('/src/db.ts')
    const { defaultOnboardingProfile } = await import('/src/onboarding.ts')
    await saveSetting('onboarded', true)
    await saveSetting('selected', 'chen')
    await saveSetting('onboardingProfile', { ...defaultOnboardingProfile('lu'), userName: '小雨', blockedTopics: '隐私话题' })
    localStorage.setItem('aily.locale', 'zh-CN')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
  })
  await page.reload()
  await page.getByRole('button', { name: '其他聊天伙伴', exact: true }).click()
  await page.getByRole('button', { name: '打开陈奕恒的会话', exact: true }).click()
  const trigger = page.getByRole('button', { name: '聊天设置', exact: true })
  const input = page.getByRole('textbox', { name: '发消息', exact: true })
  await input.fill('返回后继续聊')
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  assert.equal(await page.locator('.chat-header .lucide-ellipsis').count(), 1)
  await trigger.click()
  await page.getByText('当前不是主 Bot', { exact: true }).waitFor()
  await page.screenshot({ path: `${evidence}/menu.png` })
  await page.getByRole('button', { name: '设为主 Bot', exact: true }).click()
  await page.getByText('当前是主 Bot', { exact: true }).waitFor()
  const persisted = await page.evaluate(async () => (await (await import('/src/db.ts')).loadLocalData()).settings.onboardingProfile)
  assert.equal(persisted.characterId, 'chen')
  assert.equal(persisted.userName, '小雨')
  assert.equal(persisted.blockedTopics, '隐私话题')
  assert.equal(await input.inputValue(), '返回后继续聊')
  await page.getByRole('button', { name: '查看朋友圈', exact: true }).click()
  const feed = page.getByRole('region', { name: '角色朋友圈', exact: true })
  await feed.getByText('陈奕恒的朋友圈', { exact: true }).waitFor()
  await feed.getByRole('button', { name: '返回聊天', exact: true }).click()
  assert.equal(await input.inputValue(), '返回后继续聊')
  await trigger.click()
  await page.getByRole('button', { name: '搜索消息', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索聊天记录', exact: true }).waitFor()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 568 })
  await trigger.click()
  const box = await page.locator('.chat-settings-options').boundingBox()
  assert.ok(box && box.x >= 0 && box.x + box.width <= 320)
  await page.screenshot({ path: `${evidence}/menu-small.png` })
  await page.keyboard.press('Escape')
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  await page.reload()
  await page.getByRole('button', { name: '与陈奕恒聊天', exact: true }).click()
  await trigger.click()
  await page.getByText('当前是主 Bot', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: three-dot menu, persisted primary Bot, preserved preferences/draft, current character Moments, search, Escape, 320px layout, refresh persistence, no runtime errors.')
} finally { await browser.close() }
