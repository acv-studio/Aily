import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
const before = process.argv.includes('--before')
const evidence = 'docs/evidence/character-splash'
await mkdir(evidence, { recursive: true })
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: 'dark', reducedMotion: 'reduce', timezoneId: 'Asia/Shanghai', locale: 'zh-CN' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install({ time: new Date('2026-11-03T19:00:00+08:00') })
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4195/')
  await page.getByRole('button', { name: /遇见 TA/ }).waitFor()
  await page.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-welcome.png`, fullPage: true })
  if (await page.getByRole('checkbox', { name: '我已年满 18 周岁' }).count()) {
    await page.getByRole('checkbox', { name: '我已年满 18 周岁' }).check()
    await page.getByRole('checkbox', { name: '我理解 AI 身份与数据说明' }).check()
  }
  await page.getByRole('button', { name: /遇见 TA/ }).click()
  await page.getByRole('button', { name: /开始我们的故事/ }).click()
  // Current main has nine-step onboarding; retain compatibility with the original baseline.
  if (await page.getByRole('heading', { name: '先听听我的自我介绍' }).isVisible()) {
    for (let step = 0; step < 5; step++) await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByRole('button', { name: '发送试聊' }).click()
    await page.getByRole('button', { name: '称呼没问题，继续' }).click()
    await page.getByRole('button', { name: '完成引导' }).click()
  }
  await page.getByRole('button', { name: '我的', exact: true }).or(page.getByRole('button', { name: '确认并继续', exact: true })).waitFor()
  if (await page.getByRole('button', { name: '确认并继续', exact: true }).isVisible()) {
    await page.getByRole('checkbox', { name: '我已年满 18 周岁' }).check()
    await page.getByRole('checkbox', { name: '我理解 AI 身份与数据说明' }).check()
    await page.getByRole('button', { name: '确认并继续', exact: true }).click()
  }
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.getByText('我的 Aily', { exact: true }).waitFor()
  await page.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-profile.png`, fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: before ? '消息' : '跳过，进入消息', exact: true }).waitFor()
  await page.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-return.png`, fullPage: true })
  if (!before) {
    assert.equal(await page.getByText('正在练新菜', { exact: true }).count(), 1)
    assert.equal(await page.locator('.character-splash__portrait').evaluate(element => getComputedStyle(element).animationName), 'none')
    await page.getByRole('button', { name: '跳过，进入消息' }).click()
    await page.getByRole('button', { name: '消息', exact: true }).waitFor()
    await page.screenshot({ path: `${evidence}/after-home.png`, fullPage: true })
    await page.reload()
    await page.getByRole('button', { name: '与陆听澜继续聊天' }).click()
    await page.getByRole('button', { name: '返回消息' }).click()
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.getByLabel('主角色', { exact: true }).selectOption('gu')
    await page.getByRole('checkbox', { name: '静态画面（关闭动效）' }).check()
    await page.getByRole('checkbox', { name: '按本地时间展示角色日程' }).uncheck()
    await page.getByRole('button', { name: '保存主角色与屏保' }).click()
    await page.getByRole('status').filter({ hasText: '设置已保存' }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: '与顾辰泽继续聊天' }).waitFor()
    assert.equal(await page.getByText('在这里等你', { exact: true }).count(), 1)
    assert.equal(await page.locator('.character-splash--static').count(), 1)
    await page.setViewportSize({ width: 320, height: 740 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${evidence}/after-return-320.png`, fullPage: true })
    await page.locator('.character-splash').dispatchEvent('touchstart', { touches: [{ identifier: 1, clientX: 150, clientY: 500 }] })
    await page.locator('.character-splash').dispatchEvent('touchend', { touches: [], changedTouches: [{ identifier: 1, clientX: 155, clientY: 350 }] })
    await page.getByRole('button', { name: '消息', exact: true }).waitFor()
    await page.getByRole('button', { name: '我的', exact: true }).click()
    assert.equal(await page.getByLabel('主角色', { exact: true }).inputValue(), 'gu')
    await page.screenshot({ path: `${evidence}/after-settings-320.png`, fullPage: true })
    await page.getByRole('checkbox', { name: '再次打开时展示屏保' }).uncheck()
    await page.getByRole('button', { name: '保存主角色与屏保' }).click()
    await page.getByRole('status').filter({ hasText: '设置已保存' }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: '消息', exact: true }).waitFor()
    assert.equal(await page.locator('.character-splash').count(), 0)
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.getByRole('checkbox', { name: '再次打开时展示屏保' }).check()
    await page.getByRole('button', { name: '保存主角色与屏保' }).click()
    await page.getByRole('status').filter({ hasText: '设置已保存' }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: '跳过，进入消息' }).waitFor()
    await page.clock.runFor(15_001)
    await page.getByRole('button', { name: '消息', exact: true }).waitFor()
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.getByLabel('界面语言 / Interface language').selectOption('en')
    await page.reload()
    await page.getByRole('button', { name: 'Continue chatting with Gu Chenze' }).waitFor()
    assert.equal(await page.getByText('Waiting here for you', { exact: true }).count(), 1)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: `${evidence}/after-return-en.png`, fullPage: true })
    await page.setViewportSize({ width: 320, height: 740 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${evidence}/after-return-en-320.png`, fullPage: true })
  }
  assert.deepEqual(errors, [])
  console.log(before ? 'Captured real baseline return and profile, 390x844 dark, evening.' : 'Passed first-entry skip, return splash, character chat, primary persistence, fixed/static mode, reduced motion, swipe, disabled splash, 15s timeout and 320px layout.')
} finally { await browser.close() }
