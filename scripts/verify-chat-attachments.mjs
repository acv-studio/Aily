import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const browser = await chromium.launch()
const evidence = 'docs/evidence/chat-attachments'
await mkdir(evidence, { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4175/')
  await page.evaluate(async () => {
    const { saveSetting } = await import('/src/db.ts')
    await saveSetting('onboarded', true)
    await saveSetting('selected', 'lu')
    localStorage.setItem('aily.locale', 'zh-CN')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
  })
  await page.reload()
  await page.getByRole('button', { name: '与陆听澜聊天', exact: true }).click()
  const input = page.getByRole('textbox', { name: '发消息', exact: true })
  const plus = page.getByRole('button', { name: '更多发送选项', exact: true })
  await input.waitFor()
  const bounds = await input.boundingBox()
  const plusBounds = await plus.boundingBox()
  assert.ok(plusBounds.x > bounds.x + bounds.width)
  await plus.click()
  await page.getByRole('button', { name: '照片', exact: true }).waitFor()
  await page.screenshot({ path: `${evidence}/menu-mobile.png` })
  const footer = await page.locator('.composer').boundingBox()
  await page.screenshot({ path: `${evidence}/menu-detail.png`, clip: { x: 0, y: Math.floor(footer.y), width: 390, height: 844 - Math.floor(footer.y) } })
  await page.getByRole('button', { name: '表情', exact: true }).click()
  await page.screenshot({ path: `${evidence}/emoji-mobile.png` })
  await page.getByRole('button', { name: '插入表情 😊', exact: true }).click()
  assert.equal(await input.inputValue(), '😊')
  assert.equal(await page.locator('.message-row').count(), 0)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByRole('button', { name: '停止回复', exact: true }).waitFor({ state: 'hidden' })
  await plus.click()
  const photoChooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: '照片', exact: true }).click()
  await (await photoChooser).setFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6rWQAAAAASUVORK5CYII=', 'base64') })
  await page.locator('.attachment-preview-image').waitFor()
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.locator('.bubble .chat-image').waitFor()
  await plus.click()
  const videoChooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: '视频', exact: true }).click()
  // Generate a genuine playable WebM inside the isolated browser, not a fake media fixture.
  const bytes = await page.evaluate(async () => {
    const canvas = document.createElement('canvas')
    canvas.width = 160; canvas.height = 90
    const ctx = canvas.getContext('2d')
    ctx.fillStyle = '#9079dc'; ctx.fillRect(0, 0, 160, 90)
    const stream = canvas.captureStream(10)
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm' })
    const chunks = []
    recorder.ondataavailable = event => chunks.push(event.data)
    const stopped = new Promise(resolve => recorder.onstop = resolve)
    recorder.start()
    await new Promise(resolve => setTimeout(resolve, 300))
    recorder.stop()
    await stopped
    stream.getTracks().forEach(track => track.stop())
    return Array.from(new Uint8Array(await new Blob(chunks, { type: 'video/webm' }).arrayBuffer()))
  })
  await (await videoChooser).setFiles({ name: 'clip.webm', mimeType: 'video/webm', buffer: Buffer.from(bytes) })
  const preview = page.getByLabel('预览待发送视频', { exact: true })
  await preview.waitFor()
  await preview.evaluate(video => new Promise((resolve, reject) => {
    if (video.readyState >= 1) resolve()
    else { video.addEventListener('loadedmetadata', resolve, { once: true }); video.addEventListener('error', reject, { once: true }) }
  }))
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByLabel('播放视频消息', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: '与陆听澜聊天', exact: true }).click()
  const video = page.getByLabel('播放视频消息', { exact: true })
  await video.waitFor()
  await video.evaluate(async video => { await video.play(); video.pause() })
  assert.ok(await video.evaluate(video => video.readyState >= 2))
  await page.screenshot({ path: `${evidence}/video-after-reload.png` })
  const row = video.locator('xpath=ancestor::div[contains(@class,"message-row")]')
  await row.getByRole('button', { name: '撤回', exact: true }).click()
  await video.waitFor({ state: 'hidden' })
  for (const [width, height] of [[320, 568], [390, 360], [938, 634]]) {
    await page.setViewportSize({ width, height })
    await page.waitForFunction(() => Math.abs(document.querySelector('.chat-screen').getBoundingClientRect().height - visualViewport.height) < 2)
    await plus.click()
    const box = await plus.boundingBox()
    assert.ok(box.y >= 0 && box.y + box.height <= height)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.getByRole('button', { name: '表情', exact: true }).click()
    const panel = await page.locator('.chat-more-panel').boundingBox()
    assert.ok(panel.y >= 0 && panel.y + panel.height <= height + 1, `Panel overflow ${width}x${height}: ${JSON.stringify(panel)}`)
    await page.keyboard.press('Escape')
  }
  await page.evaluate(() => localStorage.setItem('aily.locale', 'en'))
  await page.reload()
  await page.getByRole('button', { name: 'Chat with Lu Tinglan', exact: true }).click()
  await page.getByRole('button', { name: 'More sending options', exact: true }).click()
  for (const name of ['Photos', 'Video', 'Emoji']) await page.getByRole('button', { name, exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: right-side plus, native photo/video chooser, emoji draft/send, playable WebM preview/send/reload/withdrawal, 320/390/938px layouts, English menu, no page errors.')
} finally { await browser.close() }
