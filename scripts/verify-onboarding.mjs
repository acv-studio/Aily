import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
const phase = process.env.AILY_PHASE || 'after'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: 'dark', timezoneId: 'Asia/Shanghai' })
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4178/')
  await page.getByRole('button', { name: /遇见 TA/ }).waitFor()
  await mkdir('docs/evidence/onboarding', { recursive: true })
  await page.screenshot({ path: `docs/evidence/onboarding/${phase}-welcome.png` })
  await page.getByRole('button', { name: /遇见 TA/ }).click()
  await page.getByRole('button', { name: /陈奕恒/ }).click()
  await page.screenshot({ path: `docs/evidence/onboarding/${phase}-choose.png` })
  await page.getByRole('button', { name: /开始我们的故事/ }).click()
  if (phase === 'before') {
    await page.getByRole('button', { name: '去找他' }).waitFor()
    await page.screenshot({ path: 'docs/evidence/onboarding/before-after-selection.png' })
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.screenshot({ path: 'docs/evidence/onboarding/before-profile.png' })
  } else {
    await page.getByRole('heading', { name: '先听听我的自我介绍' }).waitFor()
    await page.screenshot({ path: 'docs/evidence/onboarding/after-after-selection.png' })
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByLabel('你的名字或昵称').fill('小雨')
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByLabel('你想怎么称呼 TA').fill('阿恒')
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByLabel('聊天长度').selectOption('long')
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByLabel('禁用话题').fill('工作')
    await page.getByRole('button', { name: '了解并确认成人模式' }).click()
    await page.screenshot({ path: 'docs/evidence/onboarding/after-consent.png' })
    assert(await page.getByRole('button', { name: '确认开启' }).isDisabled())
    await page.getByRole('button', { name: '保持关闭' }).click()
    await page.getByRole('button', { name: '继续', exact: true }).click()
    await page.getByRole('button', { name: '发送试聊' }).click()
    await page.getByText('阿恒，我今天想先和你打个招呼。', { exact: true }).waitFor()
    await page.screenshot({ path: 'docs/evidence/onboarding/after-trial.png' })
    await page.getByRole('button', { name: '称呼没问题，继续' }).click()
    await page.getByRole('button', { name: '完成引导' }).click()
    await page.getByRole('button', { name: '去找他' }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: '去找他' }).waitFor()
    const data = await page.evaluate(async () => (await import('/src/db.ts')).loadLocalData())
    assert.equal(data.settings.onboardingProfile.userName, '小雨')
    assert.equal(data.settings.onboardingProfile.adultEnabled, false)
    assert.equal(data.settings.onboarded, true)
    assert.equal(data.memories.filter(m => m.category === 'relationship' && m.state === 'confirmed').length, 1)
    assert.equal(data.conversations.chen.length, 2)
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.screenshot({ path: 'docs/evidence/onboarding/after-profile.png' })
    await page.getByRole('button', { name: '修改称呼与互动偏好' }).click()
    await page.screenshot({ path: 'docs/evidence/onboarding/after-editor.png' })
    await page.getByLabel('你的名字或昵称').fill('雨雨')
    await page.getByRole('button', { name: '保存偏好' }).click()
    await page.getByRole('button', { name: '修改称呼与互动偏好' }).waitFor()
    const edited = await page.evaluate(async () => (await import('/src/db.ts')).loadLocalData())
    assert.equal(edited.settings.onboardingProfile.userName, '雨雨')
    assert.equal(edited.conversations.chen.length, 2)
    await page.setViewportSize({ width: 320, height: 640 })
    await page.getByRole('button', { name: '修改称呼与互动偏好' }).click()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
    console.log('Browser journey passed: nine steps, independent consent off, trial, IndexedDB reload, edit, 320px no overflow.')
  }
} finally { await browser.close() }
