import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const before = process.argv.includes('--before')
const evidence = 'docs/evidence/story-gifts'
await mkdir(evidence, { recursive: true })
const url = process.env.AILY_URL || `http://127.0.0.1:${before ? 14327 : 4328}/`
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: 'dark', reducedMotion: 'reduce', timezoneId: 'Asia/Shanghai' })
  await context.addInitScript(() => { localStorage.setItem('aily.locale', 'zh-CN') })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(url)
  await page.getByLabel('我已年满 18 周岁').check()
  await page.getByLabel('我理解 AI 身份与数据说明').check()
  await page.getByRole('button', { name: /遇见 TA/ }).click()
  await page.getByRole('button', { name: /陈奕恒/ }).click()
  await page.getByRole('button', { name: /开始我们的故事/ }).click()
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.getByRole('button', { name: '先不填写' }).click()
  await page.getByRole('button', { name: '先用全名' }).click()
  await page.getByRole('button', { name: '先用默认偏好' }).click()
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.getByRole('button', { name: '发送试聊' }).click()
  await page.getByRole('button', { name: '称呼没问题，继续' }).click()
  await page.getByRole('button', { name: '完成引导' }).click()
  await page.getByRole('button', { name: '商城', exact: true }).click()
  await page.getByTestId('demo-balance').filter({ hasText: /^0$/ }).waitFor()
  const balance = async () => Number((await page.getByTestId('demo-balance').textContent()).replaceAll(',', ''))
  if (!before) {
    await page.getByRole('button', { name: /演唱会票/ }).click()
    await page.getByRole('button', { name: '赠送礼物（演示）', exact: true }).click()
    await page.getByRole('button', { name: '确认赠送（演示）' }).click()
    await page.getByRole('alert').filter({ hasText: /演示币不足/ }).waitFor()
    assert.equal(await balance(), 0)
    assert.equal(await page.locator('.demo-ledger li').count(), 0)
    await page.getByRole('button', { name: /鲜花/ }).click()
  }
  await page.getByRole('button', { name: '+1,000 演示币 · 不扣款', exact: true }).click()
  await page.getByRole('button', { name: '确认模拟充值', exact: true }).click()
  await page.getByTestId('demo-balance').filter({ hasText: /^1,000$/ }).waitFor()
  await page.getByRole('heading', { name: '给 TA 一份小心意' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-store.png` })
  if (!before) {
    await page.getByRole('button', { name: /演唱会票/ }).click()
    assert.equal(await page.getByRole('spinbutton', { name: '礼物数量' }).isDisabled(), true)
    await page.getByRole('button', { name: '赠送礼物（演示）', exact: true }).click()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    assert.equal(await balance(), 1000)
    const titles = []
    // Titles are read from the actual catalog, rather than duplicated story copy.
    const cards = page.locator('.story-gift-card')
    for (const [index, gift] of ['演唱会票', '旅行箱', '相机'].entries()) {
      await page.getByRole('button', { name: new RegExp(gift) }).click()
      await page.getByRole('button', { name: '赠送礼物（演示）', exact: true }).click()
      await page.getByRole('button', { name: '确认赠送（演示）' }).click()
      await page.getByRole('button', { name: '此角色已解锁，无需重复赠送' }).waitFor()
      assert.equal(await page.getByRole('button', { name: '此角色已解锁，无需重复赠送' }).isDisabled(), true)
      const title = await cards.nth(index).getByRole('heading').textContent()
      titles[index] = title
      await cards.nth(index).getByRole('button', { name: `进入《${title}》` }).click()
      await page.getByRole('heading', { name: title, exact: true }).waitFor()
      assert.equal(await page.getByRole('heading', { name: title, exact: true }).evaluate(element => element === document.activeElement), true)
      await page.locator('.story-gift-choices button').first().click()
      if (index === 0) {
        await page.screenshot({ path: `${evidence}/after-preview.png`, fullPage: true })
        await page.getByRole('button', { name: '返回商城' }).click()
        await cards.nth(index).getByRole('button', { name: `进入《${title}》` }).click()
        assert.equal(await page.getByRole('button', { name: '确认保存事件选择' }).isDisabled(), true)
        await page.locator('.story-gift-choices button').last().click()
      }
      await page.getByRole('button', { name: '确认保存事件选择' }).click()
      await page.getByRole('status').filter({ hasText: /事件已完成/ }).waitFor()
      if (index === 0) await page.screenshot({ path: `${evidence}/after-complete.png`, fullPage: true })
      await page.getByRole('button', { name: '返回商城' }).click()
    }
    assert.equal(await balance(), 630)
    assert.equal(await page.locator('.demo-ledger li').count(), 4)
    await page.reload()
    await page.getByRole('button', { name: '商城', exact: true }).click()
    await page.getByRole('combobox', { name: '礼物接收角色' }).selectOption('chen')
    await cards.first().getByRole('button', { name: `回看《${titles[0]}》` }).click()
    await page.getByRole('status').filter({ hasText: /事件已完成/ }).waitFor()
    assert.equal(await page.locator('.story-gift-choices button').count(), 0)
    await page.getByRole('button', { name: '返回商城' }).click()
    assert.equal(await balance(), 630)
    await page.getByRole('combobox', { name: '礼物接收角色' }).selectOption('lu')
    assert.equal(await cards.getByRole('button').count(), 0)
    const other = await context.newPage()
    other.on('pageerror', error => errors.push(error.message))
    await other.goto(url)
    await other.getByRole('button', { name: '商城', exact: true }).click()
    await other.getByRole('combobox', { name: '礼物接收角色' }).selectOption('lu')
    await page.getByRole('button', { name: /演唱会票/ }).click()
    await page.getByRole('button', { name: '赠送礼物（演示）', exact: true }).click()
    await page.getByRole('button', { name: '确认赠送（演示）' }).click()
    await other.locator('.story-gift-card').first().getByRole('button', { name: /^进入/ }).waitFor()
    await other.getByTestId('demo-balance').filter({ hasText: /^530$/ }).waitFor()
    await other.close()
    await page.setViewportSize({ width: 320, height: 740 })
    await page.getByRole('heading', { name: /的剧情事件/ }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `${evidence}/after-library-320.png` })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await cards.first().getByRole('button', { name: /^进入/ }).click()
    await page.locator('.story-gift-choices button').first().click()
    await page.screenshot({ path: `${evidence}/after-event-320.png`, fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  assert.deepEqual(errors, [])
  console.log(before ? 'Captured real baseline store at 390x844, dark, Chen, 1000 coins, flower selected.' : 'Story gifts passed: insufficient funds, cancel, all three unlocks, choice preview and cancel, persistence/replay, no repeated debit, character isolation, second-tab sync, 320px layout, no page errors.')
} finally { await browser.close() }
