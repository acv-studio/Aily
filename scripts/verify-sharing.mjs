import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
const before = process.argv.includes('--before')
const dir = 'docs/evidence/sharing'
await mkdir(dir, { recursive: true })
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, colorScheme: 'dark', timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] })
  const page = await context.newPage(); const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const base = process.env.AILY_URL || 'http://127.0.0.1:4327/'
  await page.goto(base)
  await page.evaluate(async () => {
    const { db, finishOnboarding } = await import('/src/db.ts')
    const { defaultOnboardingProfile } = await import('/src/onboarding.ts')
    const { acceptSafetyConsent } = await import('/src/privacy.ts')
    acceptSafetyConsent(); await finishOnboarding({ ...defaultOnboardingProfile('lu'), userName: '小雨' }, [])
    await db.memories.put({ id: 'sharing-fixture', characterId: 'lu', text: '在海边一起写下明信片，收件人是小雨。', category: 'relationship', state: 'confirmed', enabled: true, confirmedAt: '2026-01-01T12:00:00Z' })
  })
  await page.reload(); await page.getByRole('button', { name: '去找他', exact: true }).waitFor()
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.screenshot({ path: `${dir}/${before ? 'before' : 'after'}-profile.png`, fullPage: true })
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByLabel('记忆角色').waitFor()
  await page.screenshot({ path: `${dir}/${before ? 'before' : 'after'}-memories.png`, fullPage: true })
  if (!before) {
    await page.locator('.managed-memory').filter({ hasText: '在海边一起写下明信片，收件人是小雨。' }).getByRole('button', { name: '分享回忆卡', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '分享回忆卡' })
    await page.getByAltText('待分享的回忆卡预览').waitFor()
    assert.equal(await page.getByLabel('公开文案').inputValue(), '把一个平凡的瞬间，留成值得记住的故事。')
    assert.equal(await dialog.getByRole('button', { name: '保存 PNG' }).isDisabled(), true)
    await page.screenshot({ path: `${dir}/after-card.png`, fullPage: false })
    await page.setViewportSize({ width: 320, height: 740 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${dir}/after-card-320.png`, fullPage: false })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByLabel('主动公开这条回忆的文字（最多 120 字）').check()
    assert.match(await page.getByLabel('公开文案').inputValue(), /小雨/)
    await page.getByLabel('公开文案').fill('一起写下海边明信片。')
    await page.getByLabel('我已检查预览，同意公开卡片内容').check()
    await page.getByRole('button', { name: '保存 PNG' }).waitFor({ state: 'visible' })
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '保存 PNG' }).click()])
    assert.equal(download.suggestedFilename(), 'aily-memory.png')
    await download.saveAs(`${dir}/exported-card.png`)
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '我的', exact: true }).click()
    await page.getByRole('button', { name: '邀请朋友', exact: true }).click()
    await page.getByRole('button', { name: '复制邀请链接' }).click()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), `${base}#invite=lu`)
    await page.screenshot({ path: `${dir}/after-invite.png`, fullPage: true })
    const recipient = await browser.newPage({ viewport: { width: 390, height: 844 }, colorScheme: 'dark' })
    await recipient.goto(`${base}#invite=chen`)
    await recipient.getByRole('heading', { name: '陈奕恒', exact: true }).waitFor()
    await recipient.screenshot({ path: `${dir}/after-landing.png`, fullPage: true })
    await recipient.getByRole('button', { name: '认识这位 AI 角色' }).click()
    assert.equal(await recipient.getByRole('button', { name: '遇见 TA' }).isDisabled(), true)
    await recipient.getByLabel('我已年满 18 周岁').check()
    await recipient.getByLabel('我理解 AI 身份与数据说明').check()
    await recipient.getByRole('button', { name: '遇见 TA' }).click()
    assert.equal(await recipient.getByRole('button', { name: /陈奕恒/ }).getAttribute('aria-pressed'), 'true')
    await recipient.close()
    await page.setViewportSize({ width: 320, height: 740 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  assert.deepEqual(errors, [])
  console.log(before ? 'Actual baseline captured.' : 'Sharing browser journey passed: private default, opt-in edit, confirmed PNG download, copied role link, independent recipient safety gate, 320px layout.')
} finally { await browser.close() }
