import { chromium } from 'playwright'
import { mkdir, readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

const before = process.argv.includes('--before')
const evidence = 'docs/evidence/data-transfer'
await mkdir(evidence, { recursive: true })
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: 'dark', reducedMotion: 'reduce', timezoneId: 'Asia/Shanghai', acceptDownloads: true })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:4315/')
  await page.evaluate(async () => {
    const { db } = await import('/src/db.ts')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
    await db.settings.put({ key: 'onboarded', value: true })
    await db.settings.put({ key: 'selected', value: 'lu' })
    await db.messages.put({ id: 101, characterId: 'lu', from: 'user', text: '这是用于备份验证的本机测试消息', time: '18:00', createdAt: '2026-01-01T10:00:00.000Z' })
  })
  await page.reload()
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.getByRole('heading', { name: '我的 Aily' }).waitFor()
  const panel = page.locator(before ? '.data-tools' : '.data-transfer')
  await panel.scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-profile.png`, fullPage: true })
  await panel.screenshot({ path: `${evidence}/${before ? 'before' : 'after'}-controls.png` })
  if (!before) {
    await page.getByRole('button', { name: '导出加密备份', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '至少 6 位' }).waitFor()
    await page.getByLabel('备份密码', { exact: true }).fill('test-password')
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出加密备份', exact: true }).click()
    const download = await downloadEvent
    const path = await download.path()
    const raw = await readFile(path, 'utf8')
    assert.equal(JSON.parse(raw).format, 'aily-encrypted-backup')
    assert.equal(raw.includes('本机测试消息'), false)
    await page.getByRole('status').filter({ hasText: '下载' }).waitFor()
    const snapshot = () => page.evaluate(async () => { const { db } = await import('/src/db.ts'); return db.messages.toArray() })
    const original = await snapshot()
    await page.getByLabel('导入备份文件', { exact: true }).setInputFiles({ name: 'round-trip.json', mimeType: 'application/json', buffer: Buffer.from(raw) })
    await page.getByRole('button', { name: '导入并替换本机数据' }).click()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    assert.deepEqual(await snapshot(), original)
    await page.getByLabel('备份密码', { exact: true }).fill('wrong-password')
    await page.getByRole('button', { name: '导入并替换本机数据' }).click()
    await page.getByRole('button', { name: '确认替换', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '密码错误' }).waitFor()
    assert.deepEqual(await snapshot(), original)
    await page.getByLabel('备份密码', { exact: true }).fill('test-password')
    await page.getByRole('button', { name: '确认替换', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '备份已导入' }).waitFor({ timeout: 5000 }).catch(async error => { console.log(await page.locator('body').innerText()); throw error })
    assert.deepEqual(await snapshot(), original)
    assert.equal(await page.getByLabel('备份密码', { exact: true }).inputValue(), '')
    assert.equal(await page.getByLabel('导入备份文件', { exact: true }).inputValue(), '')
    await page.getByLabel('导入备份文件', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
    await page.getByRole('button', { name: '导入并替换本机数据' }).click()
    await page.getByRole('button', { name: '确认替换', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '不是有效的 Aily' }).waitFor()
    assert.deepEqual(await snapshot(), original)
    await page.getByRole('button', { name: '取消', exact: true }).click()
    const legacy = JSON.stringify({ version: 1, conversations: { lu: original.map(({ characterId, ...message }) => message) }, memories: [], settings: { onboarded: true, selected: 'lu' } })
    await page.getByLabel('导入备份文件', { exact: true }).setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(legacy) })
    await page.getByRole('button', { name: '导入并替换本机数据' }).click()
    await page.getByRole('button', { name: '确认替换', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '备份已导入' }).waitFor()
    assert.deepEqual(await snapshot(), original)
    await page.getByRole('button', { name: '清空本机聊天与记忆', exact: true }).click()
    await page.getByRole('button', { name: '确认清空', exact: true }).scrollIntoViewIfNeeded()
    await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
    await page.screenshot({ path: `${evidence}/after-clear-confirm.png` })
    await page.getByRole('button', { name: '取消', exact: true }).click()
    assert.deepEqual(await snapshot(), original)
    await page.setViewportSize({ width: 320, height: 740 })
    await panel.scrollIntoViewIfNeeded()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${evidence}/after-profile-320.png`, fullPage: true })
    await page.getByRole('button', { name: '清空本机聊天与记忆', exact: true }).click()
    await page.getByRole('button', { name: '确认清空', exact: true }).click()
    await page.getByRole('heading', { name: /一段会记得/ }).waitFor()
    assert.equal((await snapshot()).length, 0)
  }
  assert.deepEqual(errors, [])
  console.log(before ? 'Captured runnable pre-UI baseline.' : 'Encrypted download/import, cancellation, wrong-password retry, invalid file preservation, clear and 320px layout passed.')
} finally { await browser.close() }
