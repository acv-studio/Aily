import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4173/')
  await page.evaluate(async () => {
    const { saveSetting } = await import('/src/db.ts')
    await saveSetting('onboarded', true); await saveSetting('selected', 'lu')
  })
  await page.reload()
  await page.getByRole('button', { name: '去找他' }).click()
  await page.getByRole('textbox', { name: '发消息' }).fill('我喜欢清淡的晚饭')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByText('记住这条', { exact: true }).first().waitFor()
  await page.getByRole('button', { name: '停止回复' }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '记住这条', exact: true }).first().click()
  await page.getByRole('textbox', { name: '记忆内容' }).fill('喜欢清淡晚饭，不吃辣')
  await page.getByRole('button', { name: '确认记住' }).click()
  await page.getByText('已确认保存，可在回忆页编辑或删除').waitFor()
  await page.screenshot({ path: 'docs/evidence/chat-memory/after-chat.png' })
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText('喜欢清淡晚饭，不吃辣', { exact: true }).waitFor()
  await page.screenshot({ path: 'docs/evidence/chat-memory/after-memory.png' })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('textbox', { name: '编辑记忆内容' }).fill('喜欢清淡晚饭，可以微辣')
  await page.getByRole('button', { name: '保存记忆' }).click()
  await page.getByRole('textbox', { name: '编辑记忆内容' }).waitFor({ state: 'hidden' })
  await page.getByText('喜欢清淡晚饭，可以微辣', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText('喜欢清淡晚饭，可以微辣', { exact: true }).waitFor()
  assert.equal(await page.getByText('喜欢清淡晚饭，不吃辣', { exact: true }).count(), 0)
  await page.getByRole('button', { name: '暂停引用' }).click()
  await page.getByRole('button', { name: '恢复引用' }).waitFor()
  await page.getByRole('button', { name: '消息', exact: true }).click()
  await page.getByRole('button', { name: '去找他' }).click()
  await page.getByRole('textbox', { name: '发消息' }).fill('晚饭呢？')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByRole('button', { name: '停止回复' }).waitFor({ state: 'hidden' })
  assert.equal(await page.getByText(/我记得你确认过/).count(), 0)
  await page.getByRole('button', { name: '搜索消息' }).click()
  await page.getByRole('textbox', { name: '搜索聊天记录' }).fill('我喜欢清淡')
  await page.getByText('找到 1 条消息').waitFor()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: /陈奕恒/ }).click()
  await page.getByRole('button', { name: '去找他' }).click()
  await page.getByText('从今天开始认识彼此。先说声你好吧。').waitFor()
  assert.equal(await page.getByText('我喜欢清淡的晚饭', { exact: true }).count(), 0)
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByRole('combobox', { name: '记忆角色' }).selectOption('lu')
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByText('还没有符合条件的记忆。可在聊天中选择“记住这条”。').waitFor()
  await page.reload()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByRole('combobox', { name: '记忆角色' }).selectOption('lu')
  assert.equal(await page.getByText('喜欢清淡晚饭，可以微辣', { exact: true }).count(), 0)
  assert.deepEqual(errors, [])
  console.log('Browser verification passed: send, explicit memory confirmation, edit, reload, pause, search, role isolation, delete, reload; no page errors.')
} finally { await browser.close() }
