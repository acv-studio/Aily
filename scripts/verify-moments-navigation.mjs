import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const browser = await chromium.launch()
const evidence = 'docs/evidence/moments-navigation'
await mkdir(evidence, { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4175/')
  await page.evaluate(async () => {
    const { saveSetting } = await import('/src/db.ts')
    await saveSetting('onboarded', true)
    await saveSetting('selected', 'chen')
    localStorage.setItem('aily.locale', 'zh-CN')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
  })
  await page.reload()
  const nav = page.getByRole('navigation')
  await nav.waitFor()
  assert.deepEqual(await nav.locator('button').allTextContents(), ['消息', '提醒', '记忆', '我的'])
  await nav.getByRole('button', { name: '提醒', exact: true }).click()
  await page.getByRole('heading', { name: '今日提醒', exact: true }).waitFor()
  await page.getByRole('region', { name: '今日轻量事件', exact: true }).waitFor()
  await page.screenshot({ path: `${evidence}/reminders.png` })
  await page.getByRole('button', { name: /主动提醒设置/ }).click()
  await page.getByRole('button', { name: '保存设置', exact: true }).waitFor()
  await page.getByRole('button', { name: '← 返回提醒', exact: true }).click()
  await nav.getByRole('button', { name: '消息', exact: true }).click()
  await page.getByRole('button', { name: '与陈奕恒聊天', exact: true }).click()
  const input = page.getByRole('textbox', { name: '发消息', exact: true })
  await input.fill('回来继续聊的草稿')
  assert.deepEqual(await page.locator('.quick-replies button').allTextContents(), ['⌁ 共同故事', '✊ 猜拳', '朋友圈'])
  await page.screenshot({ path: `${evidence}/chat-entry.png` })
  await page.getByRole('button', { name: '朋友圈', exact: true }).click()
  const feed = page.getByRole('region', { name: '角色朋友圈', exact: true })
  await feed.getByText('陈奕恒的朋友圈', { exact: true }).waitFor()
  await feed.getByRole('button', { name: '私聊陈奕恒', exact: true }).waitFor()
  assert.equal(await feed.locator('.daily-event').count(), 0)
  for (const name of ['陈奕恒', '顾辰泽', '陆听澜']) {
    await feed.getByRole('button', { name, exact: true }).click()
    await feed.getByText(`${name}的朋友圈`, { exact: true }).waitFor()
    assert.equal(await feed.locator('.moment').count(), 1)
    assert.ok((await feed.locator('.moment header strong').allTextContents()).every(text => text === `${name}AI`))
  }
  await feed.getByRole('button', { name: '顾辰泽', exact: true }).click()
  await page.screenshot({ path: `${evidence}/companion-moments.png` })
  await feed.getByRole('button', { name: '点赞', exact: true }).click()
  await feed.getByRole('button', { name: '取消点赞', exact: true }).waitFor()
  await feed.getByRole('button', { name: '评论', exact: true }).click()
  await feed.getByRole('textbox', { name: '评论内容', exact: true }).fill('这本书不错')
  await feed.getByRole('button', { name: '发送评论', exact: true }).click()
  await feed.getByText('本机演示回应 · 非 AI 生成', { exact: true }).waitFor()
  await feed.getByRole('button', { name: '返回聊天', exact: true }).click()
  assert.equal(await input.inputValue(), '回来继续聊的草稿')
  await page.getByRole('button', { name: '朋友圈', exact: true }).click()
  await feed.getByText('陈奕恒的朋友圈', { exact: true }).waitFor()
  await feed.getByRole('button', { name: '顾辰泽', exact: true }).click()
  await feed.getByRole('button', { name: '私聊顾辰泽', exact: true }).click()
  assert.equal(await feed.count(), 0)
  assert.ok((await input.inputValue()).startsWith('我看到你的动态了'))
  assert.equal(await page.locator('.chat-identity strong').textContent(), '顾辰泽')
  await page.getByRole('button', { name: '返回消息', exact: true }).click()
  await nav.getByRole('button', { name: '提醒', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 568 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.locator('.daily-event-choices button').first().click()
  assert.ok((await input.inputValue()).length > 0)
  assert.equal(await page.locator('.message-row').count(), 0)
  const composer = await input.boundingBox()
  assert.ok(composer && composer.y + composer.height <= 569)
  await page.getByRole('button', { name: '朋友圈', exact: true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('PASS: reminders tab and settings back route, game-adjacent Moments entry, individual feeds, likes/comment, draft preservation, owner private chat, reminders draft only, 320px layout and no page errors.')
} finally { await browser.close() }
