import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

// Isolated browser profile; never clear or modify the user's open browser data.
const browser = await chromium.launch()
const evidence = 'docs/evidence/chat-layout'
await mkdir(evidence, { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4175/')
  await page.evaluate(async () => {
    const { saveSetting } = await import('/src/db.ts')
    await saveSetting('onboarded', true)
    await saveSetting('selected', 'lu')
    localStorage.setItem('aily.locale', 'zh-CN')
    localStorage.setItem('aily-safety-consent-v1', 'adult-ai-privacy-accepted')
  })
  await page.reload()
  await page.getByRole('button', { name: '与陆听澜聊天', exact: true }).click()
  const input = page.getByRole('textbox', { name: '发消息', exact: true })
  const mode = () => page.getByRole('button', { name: /^回复模式：/ })
  await input.waitFor()
  assert.equal(await mode().getAttribute('aria-expanded'), 'false')
  assert.equal(await page.locator('.reply-mode-picker').count(), 0)
  assert.equal(await page.locator('.chat-starters button').count(), 3)
  assert.ok(await page.locator('.chat-opening').innerText().then(text => text.includes('外面降温了，外套带了吗？')))
  await page.screenshot({ path: `${evidence}/after-mobile.png` })
  const checkViewport = async (width, height) => {
    await page.setViewportSize({ width, height })
    await page.waitForFunction(() => Math.abs(document.querySelector('.chat-screen').getBoundingClientRect().height - visualViewport.height) < 2)
    const box = await input.boundingBox()
    assert.ok(box && box.y >= 0 && box.y + box.height <= height + 1, `Composer out of viewport at ${width}x${height}`)
    assert.ok(box.x >= 0 && box.x + box.width <= width + 1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    const region = await page.locator('.messages').boundingBox()
    assert.ok(region && region.height > height * .45, `Too little conversation space at ${width}x${height}`)
  }
  for (const size of [[938, 634], [320, 568], [390, 360], [390, 844]]) await checkViewport(...size)
  await page.setViewportSize({ width: 938, height: 634 })
  await page.screenshot({ path: `${evidence}/after-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '你好，很高兴认识你。', exact: true }).click()
  assert.equal(await input.inputValue(), '你好，很高兴认识你。')
  assert.equal(await page.locator('.message-row').count(), 0)
  await mode().click()
  await page.getByRole('button', { name: '深入聊天', exact: true }).click()
  await page.getByRole('button', { name: '回复模式：深入聊天', exact: true }).waitFor()
  assert.equal(await mode().getAttribute('aria-expanded'), 'false')
  assert.equal(await input.inputValue(), '你好，很高兴认识你。')
  await mode().click()
  await page.screenshot({ path: `${evidence}/after-mode.png` })
  await page.keyboard.press('Escape')
  assert.equal(await mode().getAttribute('aria-expanded'), 'false')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByRole('button', { name: '停止回复', exact: true }).waitFor({ state: 'hidden' })
  assert.ok(await page.locator('.message-row').count() >= 2)
  await page.getByRole('button', { name: '会话与隐私', exact: true }).click()
  await page.getByRole('button', { name: '临时会话', exact: true }).click()
  await page.getByRole('button', { name: '结束临时会话', exact: true }).waitFor()
  await page.getByRole('button', { name: '结束临时会话', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.reload()
  await page.getByRole('button', { name: '与陆听澜聊天', exact: true }).click()
  await page.getByRole('button', { name: '回复模式：深入聊天', exact: true }).waitFor()
  assert.ok(await page.locator('.message-row').count() >= 2)
  await page.getByRole('button', { name: '搜索消息', exact: true }).click()
  await checkViewport(320, 568)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('aily.locale', 'en'))
  await page.reload()
  await page.getByRole('button', { name: /Chat with Lu Tinglan/, exact: true }).click()
  const englishInput = page.getByRole('textbox', { name: 'Message', exact: true })
  await englishInput.waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('PASS: compact disclosures, starter draft only, mode save/reload, demo send, temporary chat, search, English, 938x634/390x844/320x568/390x360 layouts, no page errors.')
} finally { await browser.close() }
