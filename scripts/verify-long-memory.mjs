import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Shanghai' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.goto(process.env.AILY_URL || 'http://127.0.0.1:4175/')
  await page.getByRole('button', { name: /遇见 TA/ }).click()
  await page.getByRole('button', { name: /开始我们的故事/ }).click()
  await page.getByRole('button', { name: '去找他' }).click()
  const send = async text => {
    await page.getByRole('textbox', { name: '发消息' }).fill(text)
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await page.getByRole('button', { name: '停止回复' }).waitFor({ state: 'hidden' })
  }
  await send('我喜欢看海')
  await page.getByText(/1 条待确认，请到回忆页查看/).waitFor()
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText(/待确认 · 不会引用/).waitFor()
  await page.getByRole('button', { name: '确认记住', exact: true }).click()
  await page.getByText(/允许相关时引用/).waitFor()
  await page.getByText('持续对话摘要（日 / 周 / 月 / 年）').click()
  await page.getByRole('heading', { name: /年 ·/ }).waitFor()
  assert(await page.getByText(/LOCAL 本地话题摘要/).count() > 0)
  await page.getByRole('button', { name: '永远别忘' }).click()
  await page.getByRole('button', { name: '取消固定' }).waitFor()
  await page.getByRole('button', { name: '消息', exact: true }).click()
  await page.getByRole('button', { name: '去找他' }).click()
  await send('ocean')
  await page.getByText(/你确认过「我喜欢看海」，我记得/).waitFor()
  await send('我不喜欢看海')
  await page.getByText(/1 条待确认，请到回忆页查看/).waitFor()
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText(/与已有记忆冲突/).waitFor()
  await page.getByRole('button', { name: '确认记住', exact: true }).click()
  await page.getByRole('button', { name: '恢复归档' }).waitFor()
  await page.getByRole('button', { name: '消息', exact: true }).click()
  await page.getByRole('button', { name: '去找他' }).click()
  await page.getByRole('button', { name: '临时会话', exact: true }).click()
  await page.getByText(/临时会话：不落盘/).waitFor()
  const before = await page.evaluate(async () => JSON.stringify(await (await import('/src/db.ts')).loadLocalData()))
  await send('temporary secret private message')
  assert.equal(await page.getByRole('button', { name: '记住这条' }).count(), 0)
  const after = await page.evaluate(async () => JSON.stringify(await (await import('/src/db.ts')).loadLocalData()))
  assert.equal(after, before)
  await page.getByRole('button', { name: '结束临时会话' }).click()
  assert.equal(await page.getByText('temporary secret private message', { exact: true }).count(), 0)
  await page.reload()
  await page.getByRole('button', { name: '去找他' }).click()
  assert.equal(await page.getByText('temporary secret private message', { exact: true }).count(), 0)
  await page.getByRole('button', { name: '返回消息' }).click()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText('记忆与敏感信息控制').click()
  await page.getByLabel('允许用户偏好记忆', { exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('label')].find(label => label.textContent === '允许用户偏好记忆')?.querySelector('input')?.checked === false)
  await page.reload()
  await page.getByRole('button', { name: '回忆', exact: true }).click()
  await page.getByText('记忆与敏感信息控制').click()
  assert.equal(await page.getByLabel('允许用户偏好记忆', { exact: true }).isChecked(), false)
  assert.deepEqual(errors, [])
  console.log('Browser verification passed: automatic proposals, confirmation, full-history period digests, bilingual sea/ocean recall, pin, conflict archival, temporary no-write+reload, persistent category opt-out, zero page errors.')
} finally { await browser.close() }
